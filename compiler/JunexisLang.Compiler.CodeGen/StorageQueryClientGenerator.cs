namespace JunexisLang.Compiler.CodeGen;

using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using JunexisLang.Compiler.Core;
using JunexisLang.Compiler.IR;

/// <summary>Generuje typowane API Go dla nazwanych zapytań storage M13.</summary>
internal static class StorageQueryClientGenerator
{
    internal static GeneratedFile? Generate(IRDocument ir)
    {
        if (!ir.StorageDeclarations.Any(declaration => declaration.Queries.Count > 0))
            return null;

        var projection = StorageSourceProjector.Project(ir);
        if (!projection.Success)
            throw new InvalidOperationException("Storage source projection failed before Go query client generation.");

        var sb = new StringBuilder();
        var parameterTypes = projection.Plans.SelectMany(plan => plan.Parameters).ToList();
        var invocations = projection.Plans.Select(plan =>
        {
            var model = projection.Models.Single(item => item.Name == plan.Model);
            var arguments = plan.Parameters.Select(parameter => new StorageQueryArgument(
                parameter.Name,
                parameter.Type,
                SampleValue(parameter.Type))).ToList();
            var lowered = StorageRuntimeQueryLowerer.Lower(model, plan, arguments);
            if (!lowered.Success || lowered.Invocation is null)
                throw new InvalidOperationException($"Storage query lowering failed for '{model.Name}.{plan.Name}'.");
            return (Model: model, Plan: plan, Invocation: lowered.Invocation);
        }).ToList();
        var needsBase64 = parameterTypes.Any(parameter => parameter.Type == StorageValueType.Bytes);
        var needsStrconv = parameterTypes.Any(parameter => parameter.Type is StorageValueType.Int64 or StorageValueType.Float64 or StorageValueType.Bool);
        var needsTime = parameterTypes.Any(parameter => parameter.Type == StorageValueType.Timestamp);
        var needsNullable = parameterTypes.Any(parameter => parameter.Nullable);

        sb.AppendLine("// Code generated by Junexis. DO NOT EDIT.");
        sb.AppendLine("// Package queries exposes provider-neutral, typed storage reads.");
        sb.AppendLine("package queries");
        sb.AppendLine();
        sb.AppendLine("import (");
        sb.AppendLine("\t\"context\"");
        sb.AppendLine("\t\"encoding/json\"");
        if (needsBase64)
            sb.AppendLine("\t\"encoding/base64\"");
        if (needsStrconv)
            sb.AppendLine("\t\"strconv\"");
        if (needsTime)
            sb.AppendLine("\t\"time\"");
        sb.AppendLine();
        sb.AppendLine("\tjunexisStorage \"junexis/server/junexis/storage\"");
        sb.AppendLine("\tjunexisRuntime \"junexis/server/junexis/storage/runtime\"");
        sb.AppendLine(")");
        sb.AppendLine();
        if (needsNullable)
        {
            sb.AppendLine("func nullableValue[T any](value *T, format func(T) string) any {");
            sb.AppendLine("\tif value == nil { return nil }");
            sb.AppendLine("\treturn format(*value)");
            sb.AppendLine("}");
            sb.AppendLine();
        }

        foreach (var item in invocations)
            EmitQuery(sb, item.Model.Name, item.Plan, item.Invocation);

        return new GeneratedFile(
            "server",
            "server/junexis/storage/queries/generated.go",
            GeneratedGoSource.Render(sb.ToString()));
    }

    private static void EmitQuery(
        StringBuilder sb,
        string modelName,
        StorageQueryPlan plan,
        StorageRuntimeQueryInvocation invocation)
    {
        var prefix = StorageQueryNames.Callable(modelName, plan.Name);
        var inputJson = JsonSerializer.Serialize(invocation.Input, JsonOptions);
        var inputLiteral = JsonSerializer.Serialize(inputJson);

        sb.AppendLine($"// {prefix}Params contains runtime values for {modelName}.{plan.Name}.");
        sb.AppendLine($"type {prefix}Params struct {{");
        foreach (var parameter in plan.Parameters)
            sb.AppendLine($"\t{Exported(parameter.Name)} {GoType(parameter.Type, parameter.Nullable)}");
        sb.AppendLine("}");
        sb.AppendLine();

        sb.AppendLine($"// {prefix}Row is the result shape calculated by the Junexis compiler.");
        sb.AppendLine($"type {prefix}Row struct {{");
        foreach (var column in invocation.Input.Query.Result)
            sb.AppendLine($"\t{Exported(column.Name)} {GoType(column.Type, column.Nullable)} `json:\"{Escape(column.Name)}\"`");
        sb.AppendLine("}");
        sb.AppendLine();

        sb.AppendLine($"const {Lowered(prefix)}Input = {inputLiteral}");
        sb.AppendLine();
        sb.AppendLine($"// {prefix} executes {modelName}.{plan.Name} through the selected Storage Runtime provider.");
        sb.AppendLine($"func {prefix}(ctx context.Context, provider *junexisRuntime.Provider, params {prefix}Params) ([]{prefix}Row, *junexisStorage.Error) {{");
        sb.AppendLine("\tvar input map[string]any");
        sb.AppendLine($"\tif err := json.Unmarshal([]byte({Lowered(prefix)}Input), &input); err != nil {{");
        sb.AppendLine("\t\treturn nil, &junexisStorage.Error{Code: junexisStorage.ErrorInternal, Operation: \"query.plan\", Outcome: \"known\", Cause: err}");
        sb.AppendLine("\t}");
        sb.AppendLine("\tinput[\"arguments\"] = []any{");
        foreach (var parameter in plan.Parameters)
        {
            var value = $"params.{Exported(parameter.Name)}";
            sb.AppendLine($"\t\tmap[string]any{{\"name\": \"{Escape(parameter.Name)}\", \"type\": \"{TypeName(parameter.Type)}\", \"value\": {CanonicalValue(parameter.Type, parameter.Nullable, value)}}},");
        }
        sb.AppendLine("\t}");
        sb.AppendLine("\trawRows, storageErr := provider.QueryPlan(ctx, input)");
        sb.AppendLine("\tif storageErr != nil { return nil, storageErr }");
        sb.AppendLine($"\trows := make([]{prefix}Row, 0, len(rawRows))");
        sb.AppendLine("\tfor _, raw := range rawRows {");
        sb.AppendLine($"\t\tvar row {prefix}Row");
        sb.AppendLine("\t\tif err := json.Unmarshal(raw, &row); err != nil {");
        sb.AppendLine("\t\t\treturn nil, &junexisStorage.Error{Code: junexisStorage.ErrorInternal, Operation: \"query.plan\", Outcome: \"known\", Cause: err}");
        sb.AppendLine("\t\t}");
        sb.AppendLine("\t\trows = append(rows, row)");
        sb.AppendLine("\t}");
        sb.AppendLine("\treturn rows, nil");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static string GoType(StorageValueType type, bool nullable)
        => Nullable(GoType(type), nullable);

    private static string GoType(string type, bool nullable)
        => Nullable(type switch
        {
            "int64" => "int64",
            "float64" => "float64",
            "bool" => "bool",
            "text" or "decimal" or "uuid" => "string",
            "bytes" => "[]byte",
            "timestamp" => "string",
            "json" => "json.RawMessage",
            _ => "any"
        }, nullable);

    private static string GoType(StorageValueType type) => type switch
    {
        StorageValueType.Int64 => "int64",
        StorageValueType.Float64 => "float64",
        StorageValueType.Bool => "bool",
        StorageValueType.Text or StorageValueType.Decimal or StorageValueType.Uuid => "string",
        StorageValueType.Bytes => "[]byte",
        StorageValueType.Timestamp => "time.Time",
        StorageValueType.Json => "json.RawMessage",
        _ => "any"
    };

    private static string Nullable(string type, bool nullable) => nullable ? "*" + type : type;

    private static string CanonicalValue(StorageValueType type, bool nullable, string value)
    {
        var expression = type switch
        {
            StorageValueType.Int64 => $"strconv.FormatInt({value}, 10)",
            StorageValueType.Float64 => $"strconv.FormatFloat({value}, 'g', -1, 64)",
            StorageValueType.Bool => $"strconv.FormatBool({value})",
            StorageValueType.Text or StorageValueType.Decimal or StorageValueType.Uuid => value,
            StorageValueType.Bytes => $"base64.StdEncoding.EncodeToString({value})",
            StorageValueType.Timestamp => $"{value}.Format(time.RFC3339Nano)",
            StorageValueType.Json => $"string({value})",
            _ => "nil"
        };
        if (!nullable)
            return expression;

        var dereferenced = CanonicalValue(type, false, "*" + value);
        return $"nullableValue({value}, func(value {GoType(type)}) string {{ return {dereferenced.Replace("*" + value, "value", StringComparison.Ordinal)} }})";
    }

    private static string SampleValue(StorageValueType type) => type switch
    {
        StorageValueType.Int64 => "0",
        StorageValueType.Float64 => "0",
        StorageValueType.Bool => "false",
        StorageValueType.Text => "",
        StorageValueType.Bytes => "",
        StorageValueType.Decimal => "0",
        StorageValueType.Timestamp => "1970-01-01T00:00:00.0000000+00:00",
        StorageValueType.Uuid => "00000000-0000-0000-0000-000000000000",
        StorageValueType.Json => "{}",
        _ => throw new ArgumentOutOfRangeException(nameof(type), type, null)
    };

    private static string TypeName(StorageValueType type) => type switch
    {
        StorageValueType.Int64 => "int64",
        StorageValueType.Float64 => "float64",
        StorageValueType.Bool => "bool",
        StorageValueType.Text => "text",
        StorageValueType.Bytes => "bytes",
        StorageValueType.Decimal => "decimal",
        StorageValueType.Timestamp => "timestamp",
        StorageValueType.Uuid => "uuid",
        StorageValueType.Json => "json",
        _ => throw new ArgumentOutOfRangeException(nameof(type), type, null)
    };

    private static string Exported(string value) => value.Length == 0
        ? value
        : char.ToUpperInvariant(value[0]) + value[1..];

    private static string Lowered(string value) => value.Length == 0
        ? value
        : char.ToLowerInvariant(value[0]) + value[1..];

    private static string Escape(string value) => value
        .Replace("\\", "\\\\", StringComparison.Ordinal)
        .Replace("\"", "\\\"", StringComparison.Ordinal);

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        WriteIndented = false
    };
}
