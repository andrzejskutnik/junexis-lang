namespace JunexisLang.Compiler.CodeGen;

using System.Globalization;
using System.Text;
using JunexisLang.Compiler.Core;
using JunexisLang.Compiler.IR;
using JunexisLang.Compiler.Topology;

/// <summary>
/// Emits a small debugger/narrative manifest that maps runtime trace identifiers
/// back to Junexis language concepts.
/// </summary>
public static class DebugManifestGenerator
{
    /// <summary>Generates the canonical debug manifest artifact.</summary>
    public static GeneratedFile Generate(IRDocument document)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by JunexisLang compiler — debug/narrative manifest");
        sb.AppendLine("schemaVersion = \"0.3\"");
        sb.AppendLine("kind = \"junexis.debug-manifest\"");
        sb.AppendLine($"sourceFile = {Q(document.SourceFile)}");
        sb.AppendLine();
        sb.AppendLine("[debugger]");
        sb.AppendLine($"traceCollectorEventModel = {Q(TraceRuntimeContract.EventModel)}");
        sb.AppendLine("taskIdStrategy = \"1-based IR task order\"");
        sb.AppendLine($"messageCorrelationAttribute = {Q(TraceRuntimeContract.PayloadHashAttribute)}");
        sb.AppendLine($"narrativeAttribute = {Q(TraceRuntimeContract.NarrativeIdAttribute)}");
        sb.AppendLine();

        for (var i = 0; i < document.Tasks.Count; i++)
        {
            var task = document.Tasks[i];
            var source = Source(document, $"/Tasks[{i}]");
            sb.AppendLine("[[tasks]]");
            sb.AppendLine($"id = {i + 1}");
            sb.AppendLine($"symbolId = {Q(StableSymbolIds.Symbol("task", task.Name))}");
            sb.AppendLine($"name = {Q(task.Name)}");
            sb.AppendLine($"targets = {StringArray(task.Platforms.Select(platform => platform.Target).Distinct(StringComparer.OrdinalIgnoreCase))}");
            if (task.OutputType is not null)
                sb.AppendLine($"output = {Q(TypeName(task.OutputType))}");
            AppendSource(sb, source);
            sb.AppendLine();
        }

        for (var i = 0; i < document.Pipelines.Count; i++)
        {
            var pipeline = document.Pipelines[i];
            var source = Source(document, $"/Pipelines[{i}]");
            sb.AppendLine("[[pipelines]]");
            sb.AppendLine($"symbolId = {Q(StableSymbolIds.Symbol("pipeline", pipeline.Name))}");
            sb.AppendLine($"name = {Q(pipeline.Name)}");
            AppendSource(sb, source);
            sb.AppendLine();

            foreach (var edge in Flatten(pipeline.Connections).OfType<IRUseConn>())
            {
                sb.AppendLine("[[pipelineEdges]]");
                sb.AppendLine($"pipeline = {Q(pipeline.Name)}");
                sb.AppendLine($"sourceTask = {Q(edge.SourceTask)}");
                if (edge.SourcePort is not null)
                    sb.AppendLine($"sourcePort = {Q(edge.SourcePort)}");
                if (edge.TargetTask is not null)
                    sb.AppendLine($"targetTask = {Q(edge.TargetTask)}");
                if (edge.TargetPort is not null)
                    sb.AppendLine($"targetPort = {Q(edge.TargetPort)}");
                sb.AppendLine();
            }
        }

        var communicationIds = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (var edge in PipelineGraph.Build(document).Edges)
        {
            var semanticId = StableSymbolIds.Communication(
                edge.Pipeline, edge.From, edge.FromPort, edge.To, edge.ToPort);
            communicationIds.TryGetValue(semanticId, out var duplicateIndex);
            communicationIds[semanticId] = duplicateIndex + 1;
            var id = duplicateIndex == 0 ? semanticId : $"{semanticId}#{duplicateIndex + 1}";

            sb.AppendLine("[[communications]]");
            sb.AppendLine($"id = {Q(id)}");
            sb.AppendLine($"kind = {Q(CommunicationKind(document, edge))}");
            sb.AppendLine($"pipelineSymbolId = {Q(StableSymbolIds.Symbol("pipeline", edge.Pipeline))}");
            sb.AppendLine($"sourceSymbolId = {Q(StableSymbolIds.Symbol("task", edge.From))}");
            sb.AppendLine($"targetSymbolId = {Q(StableSymbolIds.Symbol("task", edge.To))}");
            sb.AppendLine($"pipeline = {Q(edge.Pipeline)}");
            sb.AppendLine($"sourceTask = {Q(edge.From)}");
            if (edge.FromPort is not null)
                sb.AppendLine($"sourcePort = {Q(edge.FromPort)}");
            sb.AppendLine($"targetTask = {Q(edge.To)}");
            if (edge.ToPort is not null)
                sb.AppendLine($"targetPort = {Q(edge.ToPort)}");
            AppendSource(sb, edge.Source);
            sb.AppendLine();
        }

        for (var i = 0; i < document.Devices.Count; i++)
        {
            var device = document.Devices[i];
            var source = Source(document, $"/Devices[{i}]");
            sb.AppendLine("[[devices]]");
            sb.AppendLine($"symbolId = {Q(StableSymbolIds.Symbol("device", device.Name))}");
            sb.AppendLine($"name = {Q(device.Name)}");
            sb.AppendLine($"target = {Q(device.Platform.Target)}");
            sb.AppendLine($"platform = {Q(device.Platform.ToString())}");
            AppendSource(sb, source);
            sb.AppendLine();
        }

        for (var i = 0; i < document.ExternContracts.Count; i++)
        {
            var contract = document.ExternContracts[i];
            var source = Source(document, $"/ExternContracts[{i}]");
            sb.AppendLine("[[externs]]");
            sb.AppendLine($"role = {Q(contract.Role)}");
            sb.AppendLine($"name = {Q(contract.Name)}");
            if (contract.Target is not null)
                sb.AppendLine($"target = {Q(contract.Target)}");
            if (contract.Language is not null)
                sb.AppendLine($"language = {Q(contract.Language)}");
            if (contract.UserFile is not null)
                sb.AppendLine($"userFile = {Q(contract.UserFile)}");
            sb.AppendLine($"functions = {StringArray(contract.Functions.Select(function => function.Name))}");
            AppendSource(sb, source);
            sb.AppendLine();
        }

        for (var i = 0; i < document.Narratives.Count; i++)
        {
            var narrative = document.Narratives[i];
            var source = Source(document, $"/Narratives[{i}]");
            sb.AppendLine("[[narratives]]");
            sb.AppendLine($"symbolId = {Q(StableSymbolIds.Symbol("narrative", narrative.Label))}");
            sb.AppendLine($"label = {Q(narrative.Label)}");
            sb.AppendLine($"body = {Q(narrative.RawBody)}");
            AppendSource(sb, source);
            sb.AppendLine();
        }

        return new GeneratedFile("debug", "debug/junexis.debug.toml", sb.ToString());
    }

    private static IEnumerable<IRPipelineConn> Flatten(IEnumerable<IRPipelineConn> connections)
    {
        foreach (var connection in connections)
        {
            if (connection is IRParallelBlock parallel)
            {
                foreach (var nested in Flatten(parallel.Connections))
                    yield return nested;
            }
            else
            {
                yield return connection;
            }
        }
    }

    private static IRSourceSpan? Source(IRDocument document, string path) =>
        document.SourceMap.FirstOrDefault(entry => entry.Path == path)?.Source;

    private static void AppendSource(StringBuilder sb, IRSourceSpan? source)
    {
        if (source is null)
            return;

        sb.AppendLine($"sourceFile = {Q(source.File)}");
        sb.AppendLine($"sourceLine = {source.Line.ToString(CultureInfo.InvariantCulture)}");
        sb.AppendLine($"sourceColumn = {source.Column.ToString(CultureInfo.InvariantCulture)}");
    }

    private static string TypeName(IRType type) => type switch
    {
        IRNamedType named => named.Name,
        IRCommType comm => $"{comm.Kind.ToString().ToLowerInvariant()}<{TypeName(comm.Element)}>",
        IRMapType map => $"Map<{TypeName(map.Key)}, {TypeName(map.Value)}>",
        IRGenericType generic => $"{generic.Name}<{string.Join(", ", generic.TypeArgs.Select(TypeName))}>",
        IRArrayType array => $"List<{TypeName(array.Element)}>",
        IRUnionType union => string.Join(" | ", union.Variants.Select(TypeName)),
        _ => type.GetType().Name
    };

    private static string StringArray(IEnumerable<string> values) =>
        $"[{string.Join(", ", values.Select(Q))}]";

    /// <summary>Determines the Junexis communication kind represented by a logical pipeline edge.</summary>
    public static string CommunicationKind(IRDocument document, PipelineEdge edge)
    {
        var bridgeKind = document.QueueBridges.Any(bridge => Matches(bridge.PipelineName, bridge.SourceTask, bridge.SourcePort, bridge.TargetTask, bridge.TargetPort, edge))
            ? "queue"
            : document.StreamBridges.Any(bridge => Matches(bridge.PipelineName, bridge.SourceTask, bridge.SourcePort, bridge.TargetTask, bridge.TargetPort, edge))
                ? "stream"
                : document.ChanBridges.Any(bridge => Matches(bridge.PipelineName, bridge.SourceTask, bridge.SourcePort, bridge.TargetTask, bridge.TargetPort, edge))
                    ? "chan"
                    : null;
        if (bridgeKind is not null)
            return bridgeKind;

        var sourceTask = document.Tasks.FirstOrDefault(task => task.Name == edge.From);
        if (sourceTask?.OutputType is IRCommType output)
            return output.Kind.ToString().ToLowerInvariant();

        var targetTask = document.Tasks.FirstOrDefault(task => task.Name == edge.To);
        var targetParameter = edge.ToPort is null
            ? targetTask?.Params.FirstOrDefault(parameter => parameter.Type is IRCommType)
            : targetTask?.Params.FirstOrDefault(parameter => parameter.Name == edge.ToPort);
        return targetParameter?.Type is IRCommType input
            ? input.Kind.ToString().ToLowerInvariant()
            : "unknown";
    }

    private static bool Matches(
        string pipeline,
        string sourceTask,
        string? sourcePort,
        string targetTask,
        string? targetPort,
        PipelineEdge edge) =>
        pipeline == edge.Pipeline && sourceTask == edge.From && sourcePort == edge.FromPort &&
        targetTask == edge.To && targetPort == edge.ToPort;

    private static string Q(string value) =>
        "\"" + value
            .Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal)
            .Replace("\r", "\\r", StringComparison.Ordinal)
            .Replace("\n", "\\n", StringComparison.Ordinal) + "\"";
}
