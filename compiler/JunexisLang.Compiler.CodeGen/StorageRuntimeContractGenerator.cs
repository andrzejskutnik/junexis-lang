namespace JunexisLang.Compiler.CodeGen;

using JunexisLang.Compiler.Core;
using JunexisLang.Compiler.IR;

internal static class StorageRuntimeContractGenerator
{
    internal static GeneratedFile? Generate(IRDocument ir)
    {
        if (!HasServerStorage(ir))
            return null;

        return new GeneratedFile("server", "server/junexis/storage/contract.go", GeneratedGoSource.Render(Source));
    }

    internal static bool HasServerStorage(IRDocument ir) =>
        ir.StorageDeclarations.Any(declaration => declaration.Queries.Count > 0 || declaration.Mutations.Count > 0) ||
        IRStorageContractProjection.Project(ir).Any(contract =>
            contract.Target is null || contract.Target.Equals("server", StringComparison.OrdinalIgnoreCase));

    private const string Source = """
        // Code generated by Junexis. DO NOT EDIT.
        // Package storage defines the provider-neutral junexis.storage/0.1 runtime contract.
        package storage

        import (
            "context"
            "fmt"
            "time"
        )

        // ErrorCode is a stable junexis.storage/0.1 error class.
        type ErrorCode string

        const (
            ErrorNotFound       ErrorCode = "not-found"
            ErrorConflict       ErrorCode = "conflict"
            ErrorConstraint     ErrorCode = "constraint"
            ErrorBusy           ErrorCode = "busy"
            ErrorTimeout        ErrorCode = "timeout"
            ErrorCancelled      ErrorCode = "cancelled"
            ErrorMigration      ErrorCode = "migration"
            ErrorUnavailable    ErrorCode = "unavailable"
            ErrorUnknownOutcome ErrorCode = "unknown-outcome"
            ErrorInternal       ErrorCode = "internal"
        )

        // Error preserves the stable class without exposing operation values or secrets.
        type Error struct {
            Code      ErrorCode
            Operation string
            Retryable bool
            Outcome   string
            Cause     error
        }

        func (e *Error) Error() string {
            if e == nil {
                return ""
            }
            return fmt.Sprintf("junexis storage %s failed: %s", e.Operation, e.Code)
        }

        func (e *Error) Unwrap() error {
            if e == nil {
                return nil
            }
            return e.Cause
        }

        // Event contains secret-safe operation telemetry.
        type Event struct {
            Operation string
            Duration  time.Duration
            ErrorCode ErrorCode
        }

        // Record is the provider-neutral representation used at the adapter boundary.
        type Record struct {
            Key     string
            Payload []byte
        }

        // Transaction exposes the same domain operations inside an atomic boundary.
        type Transaction interface {
            Put(context.Context, string, string, []byte) *Error
            Get(context.Context, string, string) (Record, *Error)
            List(context.Context, string) ([]Record, *Error)
            Delete(context.Context, string, string) *Error
        }

        // TransactionWork is committed only when it returns nil.
        type TransactionWork func(Transaction) *Error

        // Store is implemented by every conforming provider used by a domain adapter.
        type Store interface {
            Put(context.Context, string, string, []byte) *Error
            Get(context.Context, string, string) (Record, *Error)
            List(context.Context, string) ([]Record, *Error)
            Delete(context.Context, string, string) *Error
            Transact(context.Context, TransactionWork) *Error
            Health(context.Context) *Error
            Close() *Error
        }
        """;
}
