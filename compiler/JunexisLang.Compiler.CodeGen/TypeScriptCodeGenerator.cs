    private static GeneratedFile GenerateReportServer() => new(
        "report",
        "report/serve.mjs",
        """
        // Generated by JunexisLang compiler — bounded static server for @report.
        import { createReadStream, statSync } from 'node:fs';
        import { createServer } from 'node:http';
        import { extname, join, normalize, resolve } from 'node:path';
        import { fileURLToPath } from 'node:url';

        const root = resolve(fileURLToPath(new URL('.', import.meta.url)));
        const port = Number.parseInt(process.env.JUNEXIS_REPORT_PORT ?? '4174', 10);
        const serverUrl = process.env.JUNEXIS_SERVER_URL ?? 'http://localhost:8080';
        const contentTypes = new Map([
          ['.html', 'text/html; charset=utf-8'], ['.js', 'text/javascript; charset=utf-8'],
          ['.css', 'text/css; charset=utf-8'], ['.json', 'application/json; charset=utf-8'],
          ['.svg', 'image/svg+xml'], ['.png', 'image/png']
        ]);

        function resolveFile(pathname) {
          const requested = pathname === '/' ? 'index.html' : pathname.replace(/^\/+/, '');
          const candidate = resolve(root, normalize(requested));
          if (candidate !== root && !candidate.startsWith(root + '\\') && !candidate.startsWith(root + '/')) return undefined;
          return candidate;
        }

        const server = createServer((request, response) => {
          const url = new URL(request.url ?? '/', `http://${request.headers.host ?? `127.0.0.1:${port}`}`);
          if (url.pathname === '/health/ready') {
            response.writeHead(200, { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store' });
            response.end(JSON.stringify({ status: 'ready', target: 'report' }));
            return;
          }
          if (url.pathname === '/' && !url.searchParams.has('server')) {
            url.searchParams.set('server', serverUrl);
            response.writeHead(302, { location: `${url.pathname}${url.search}` });
            response.end();
            return;
          }
          const file = resolveFile(url.pathname);
          try {
            if (!file || !statSync(file).isFile()) throw new Error('not found');
            response.writeHead(200, {
              'content-type': contentTypes.get(extname(file)) ?? 'application/octet-stream',
              'x-content-type-options': 'nosniff',
              'referrer-policy': 'no-referrer',
              'cache-control': file.endsWith('index.html') ? 'no-store' : 'public, max-age=300'
            });
            createReadStream(file).pipe(response);
          } catch {
            response.writeHead(404, { 'content-type': 'text/plain; charset=utf-8' });
            response.end('Nie znaleziono zasobu raportu.');
          }
        });

        server.listen(port, '127.0.0.1', () => {
          console.log(`JUNEXIS_REPORT_READY http://127.0.0.1:${port}/?server=${encodeURIComponent(serverUrl)}`);
        });
        const stop = () => server.close(() => process.exit(0));
        process.on('SIGINT', stop);
        process.on('SIGTERM', stop);
        """);

    private static GeneratedFile GenerateReportView() => new(
        "report",
        "report/report-view.ts",
        """
        // Generated by JunexisLang compiler — safe automatic @report renderer.
        import { userReportAdapter } from './user-adapter.js';
        import { userReportView } from './user-view.js';
        import type { ReportFieldDefinition, ReportPanelDefinition } from './report-view-contract.js';
        import type { ReportAdapterObservation, ReportConnectionState } from './report-adapter-contract.js';

        export type { ReportConnectionState } from './report-adapter-contract.js';

        const HISTORY_LIMIT = 50;
        const MAX_COLLECTION_ITEMS = 20;
        const MAX_DEPTH = 4;
        const MAX_TEXT_LENGTH = 4_000;
        const histories = new Map<string, unknown[]>();
        let adapterOwnsView = false;
        let adapterFailure: string | null = null;

        function declarativePanel(taskName: string): ReportPanelDefinition | undefined {
          return userReportView?.panels.find(panel => panel.task === taskName);
        }

        function readPath(value: unknown, path: string): unknown {
          if (!path) return value;
          return path.split('.').reduce<unknown>((current, segment) => {
            if (current === null || typeof current !== 'object' || Array.isArray(current)) return undefined;
            return (current as Record<string, unknown>)[segment];
          }, value);
        }

        function formatField(value: unknown, field: ReportFieldDefinition): string {
          if (value === null || value === undefined) return 'brak wartości';
          let rendered: string;
          switch (field.format ?? 'auto') {
            case 'number': rendered = typeof value === 'number' ? value.toLocaleString() : text(value); break;
            case 'boolean': rendered = value === true ? 'tak' : value === false ? 'nie' : text(value); break;
            case 'json': rendered = text(JSON.stringify(value, null, 2)); break;
            default: rendered = text(value); break;
          }
          return field.unit ? rendered + ' ' + field.unit : rendered;
        }

        function reportAdapterError(operation: string, error: unknown): void {
          const message = error instanceof Error ? error.message : String(error);
          adapterFailure = `Błąd adaptera interfejsu: ${message}`;
          console.error(`[junexis:report-adapter] ${operation} failed`, error);
          const status = byId('connection-status');
          const label = byId('connection-label');
          if (status) status.dataset.state = 'error';
          if (label) label.textContent = adapterFailure;
        }

        function byId(id: string): HTMLElement | null {
          return typeof document === 'undefined' ? null : document.getElementById(id);
        }

        function clear(node: HTMLElement): void {
          while (node.firstChild) node.removeChild(node.firstChild);
        }

        function text(value: unknown): string {
          const result = typeof value === 'string' ? value : String(value);
          return result.length <= MAX_TEXT_LENGTH ? result : `${result.slice(0, MAX_TEXT_LENGTH)}…`;
        }

        function renderValue(value: unknown, depth = 0): HTMLElement {
          const node = document.createElement('div');
          node.className = 'value';
          if (value === null || value === undefined) {
            node.classList.add('value-empty');
            node.textContent = 'brak wartości';
            return node;
          }
          if (depth >= MAX_DEPTH) {
            node.classList.add('value-muted');
            node.textContent = 'dalsze zagnieżdżenie ukryte';
            return node;
          }
          if (Array.isArray(value)) {
            const list = document.createElement('ol');
            list.className = 'value-list';
            value.slice(0, MAX_COLLECTION_ITEMS).forEach(item => {
              const row = document.createElement('li');
              row.appendChild(renderValue(item, depth + 1));
              list.appendChild(row);
            });
            if (value.length > MAX_COLLECTION_ITEMS) {
              const remainder = document.createElement('li');
              remainder.textContent = `Ukryto ${value.length - MAX_COLLECTION_ITEMS} dalszych elementów.`;
              list.appendChild(remainder);
            }
            node.appendChild(list);
            return node;
          }
          if (typeof value === 'object') {
            const grid = document.createElement('dl');
            grid.className = 'value-grid';
            Object.entries(value as Record<string, unknown>).slice(0, MAX_COLLECTION_ITEMS).forEach(([key, item]) => {
              const term = document.createElement('dt');
              term.textContent = key;
              const description = document.createElement('dd');
              description.appendChild(renderValue(item, depth + 1));
              grid.append(term, description);
            });
            node.appendChild(grid);
            return node;
          }
          node.classList.add(`value-${typeof value}`);
          node.textContent = text(value);
          return node;
        }

        function ensurePanel(taskName: string): HTMLElement | null {
          const host = byId('report-panels');
          if (!host) return null;
          const id = `report-${taskName.replace(/[^a-zA-Z0-9_-]/g, '-')}`;
          const existing = document.getElementById(id);
          if (existing) return existing;
          const panel = document.createElement('section');
          panel.id = id;
          panel.className = 'report-panel';
          panel.setAttribute('aria-labelledby', `${id}-heading`);
          const heading = document.createElement('h3');
          heading.id = `${id}-heading`;
          heading.textContent = declarativePanel(taskName)?.title ?? taskName;
          const empty = document.createElement('p');
          empty.className = 'empty-state';
          empty.textContent = 'Oczekiwanie na pierwszą obserwację.';
          panel.append(heading, empty);
          host.appendChild(panel);
          return panel;
        }

        export function initializeReportApplication(taskNames: string[]): void {
          if (typeof document === 'undefined') return;
          if (userReportView) {
            const title = byId('report-title');
            const panels = byId('report-panels');
            if (title) title.textContent = userReportView.title;
            if (panels) panels.dataset.layout = userReportView.layout;
          }
          try {
            adapterOwnsView = userReportAdapter.mount?.({
              root: byId('report-content'),
              panels: byId('report-panels'),
              taskNames: [...taskNames]
            }) === true;
          } catch (error) {
            reportAdapterError('mount', error);
          }
          if (!adapterOwnsView) taskNames.forEach(ensurePanel);
          setReportConnectionState('connecting', 'Łączenie z systemem…');
        }

        export function setReportConnectionState(state: ReportConnectionState, detail = ''): void {
          if (adapterFailure) {
            state = 'error';
            detail = adapterFailure;
          }
          if (typeof document === 'undefined') {
            if (detail) console.log(`[junexis:report] ${state}: ${detail}`);
            return;
          }
          const status = byId('connection-status');
          const label = byId('connection-label');
          if (status) status.dataset.state = state;
          const labels: Record<ReportConnectionState, string> = {
            starting: 'Uruchamianie raportu…',
            connecting: 'Łączenie z systemem…',
            connected: 'Połączono — dane aktualne',
            reconnecting: 'Połączenie przerwane — ponawianie…',
            incompatible: 'Niezgodna wersja danych',
            error: 'Błąd raportu',
            idle: 'Raport bez aktywnego źródła'
          };
          if (label) label.textContent = detail || labels[state];
          if (state === 'reconnecting' || state === 'error' || state === 'incompatible') {
            document.querySelectorAll('.report-panel').forEach(panel => panel.setAttribute('data-stale', 'true'));
          }
          if (!adapterFailure) {
            try {
              userReportAdapter.onConnection?.({ state, detail: detail || labels[state] });
            } catch (error) {
              reportAdapterError('onConnection', error);
            }
          }
        }

        export function renderReportItem(taskName: string, item: unknown): void {
          if (typeof document === 'undefined') {
            console.log(item);
            return;
          }
          const history = histories.get(taskName) ?? [];
          history.unshift(item);
          if (history.length > HISTORY_LIMIT) history.length = HISTORY_LIMIT;
          histories.set(taskName, history);
          const receivedAt = new Date();
          const observation: ReportAdapterObservation = {
            taskName,
            item,
            receivedAt,
            history: [...history],
            historyLimit: HISTORY_LIMIT
          };
          if (!adapterFailure) {
            try {
              if (userReportAdapter.onObservation?.(observation) === true || adapterOwnsView) return;
            } catch (error) {
              reportAdapterError('onObservation', error);
            }
          }
          const panel = ensurePanel(taskName);
          if (!panel) return;
          panel.removeAttribute('data-stale');
          clear(panel);
          const heading = document.createElement('h3');
          heading.id = `${panel.id}-heading`;
          heading.textContent = taskName;
          const timestamp = document.createElement('time');
          timestamp.dateTime = receivedAt.toISOString();
          timestamp.textContent = `Odebrano ${receivedAt.toLocaleTimeString()}`;
          const current = document.createElement('div');
          current.className = 'current-value';
          const definition = declarativePanel(taskName);
          if (definition && definition.fields.length > 0) {
            const fields = document.createElement('dl');
            fields.className = 'value-grid declarative-fields';
            definition.fields.forEach(field => {
              const term = document.createElement('dt');
              term.textContent = field.label;
              const description = document.createElement('dd');
              description.className = 'declarative-field';
              description.textContent = formatField(readPath(item, field.path), field);
              fields.append(term, description);
            });
            current.appendChild(fields);
          } else {
            current.appendChild(renderValue(item));
          }
          const count = document.createElement('p');
          count.className = 'history-count';
          count.textContent = `Historia w pamięci: ${history.length} / ${HISTORY_LIMIT}`;
          panel.append(heading, timestamp, current, count);
          const summary = byId('report-summary');
          if (summary) summary.textContent = `Ostatnia aktualizacja pochodzi z zadania ${taskName}.`;
        }
        """);

