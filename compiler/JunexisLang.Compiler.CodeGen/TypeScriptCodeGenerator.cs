    }

    private static GeneratedFile GenerateDeployBootstrap(IReadOnlyList<IRTask> tasks, bool requiresServerRuntime)
    {
        var runnableTasks = tasks
            .Where(task => task.Params.All(parameter => parameter.Type is IRCommType))
            .ToList();
        var skippedTasks = tasks.Count - runnableTasks.Count;
        var sb = new StringBuilder();
        sb.AppendLine("// Generated by JunexisLang compiler — bounded local deployment bootstrap");
        if (runnableTasks.Count > 0)
            sb.AppendLine($"import {{ {string.Join(", ", runnableTasks.Select(task => task.Name))} }} from './index.js';");
        if (runnableTasks.Any(task => task.Params.Count > 0))
            sb.AppendLine("import { Channel, Queue, Stream } from './runtime.js';");
        sb.AppendLine();
        sb.AppendLine("type JunexisProcess = {");
        sb.AppendLine("  env: Record<string, string | undefined>;");
        sb.AppendLine("  on(signal: 'SIGINT' | 'SIGTERM', handler: () => void): void;");
        sb.AppendLine("  exit(code?: number): never;");
        sb.AppendLine("};");
        sb.AppendLine("const runtimeProcess = (globalThis as unknown as { process?: JunexisProcess }).process;");
        sb.AppendLine("if (!runtimeProcess) throw new Error('Junexis local deployment requires a Node.js process');");
        if (requiresServerRuntime)
            sb.AppendLine("if (!runtimeProcess.env.JUNEXIS_SERVER_URL) throw new Error('Junexis report bridge requires a deployed server runtime');");
        sb.AppendLine();

        foreach (var task in runnableTasks)
        {
            var arguments = string.Join(", ", task.Params.Select(parameter =>
                parameter.Type is IRCommType { Kind: IRCommKind.Queue }
                    ? "new Queue<any>()"
                    : parameter.Type is IRCommType { Kind: IRCommKind.Chan }
                        ? "new Channel<any>()"
                        : "new Stream<any>()"));
            sb.AppendLine($"void {task.Name}({arguments}).catch(error => {{");
            sb.AppendLine($"  console.error('[junexis:report] task {EscapeStringLiteral(task.Name)} failed', error);");
            sb.AppendLine("  runtimeProcess.exit(1);");
            sb.AppendLine("});");
        }

        sb.AppendLine();
        sb.AppendLine("console.log(JSON.stringify({");
        sb.AppendLine("  schemaVersion: 'junexis.local-runtime/0.1',");
        sb.AppendLine("  target: 'report',");
        sb.AppendLine("  status: 'ready',");
        sb.AppendLine("  buildId: runtimeProcess.env.JUNEXIS_BUILD_ID ?? '',");
        sb.AppendLine("  bundleId: runtimeProcess.env.JUNEXIS_BUNDLE_ID ?? '',");
        sb.AppendLine($"  startedTasks: {runnableTasks.Count},");
        sb.AppendLine($"  skippedTasks: {skippedTasks}");
        sb.AppendLine("}));");
        sb.AppendLine("const keepAlive = setInterval(() => undefined, 1000);");
        sb.AppendLine("const stop = (): void => { clearInterval(keepAlive); runtimeProcess.exit(0); };");
        sb.AppendLine("runtimeProcess.on('SIGINT', stop);");
        sb.AppendLine("runtimeProcess.on('SIGTERM', stop);");
        return new GeneratedFile("report", "report/deploy.ts", sb.ToString());
    }

    private static GeneratedFile GenerateBrowserBootstrap(IReadOnlyList<IRTask> tasks)
    {
        var runnableTasks = tasks
            .Where(task => task.Params.All(parameter => parameter.Type is IRCommType))
            .ToList();
        var sb = new StringBuilder();
        sb.AppendLine("// Generated by JunexisLang compiler — @report browser bootstrap");
        if (runnableTasks.Count > 0)
            sb.AppendLine($"import {{ {string.Join(", ", runnableTasks.Select(task => task.Name))} }} from './index.js';");
        if (runnableTasks.Any(task => task.Params.Count > 0))
            sb.AppendLine("import { Channel, Queue, Stream } from './runtime.js';");
        sb.AppendLine("import { initializeReportApplication, setReportConnectionState } from './report-view.js';");
        sb.AppendLine();
        sb.AppendLine($"initializeReportApplication([{string.Join(", ", tasks.Select(task => $"'{EscapeStringLiteral(task.Name)}'"))}]);");
        if (runnableTasks.Count == 0)
            sb.AppendLine("setReportConnectionState('idle', 'Brak zadań raportowych możliwych do uruchomienia w przeglądarce.');");
        foreach (var task in runnableTasks)
        {
            var arguments = string.Join(", ", task.Params.Select(parameter =>
                parameter.Type is IRCommType { Kind: IRCommKind.Queue }
                    ? "new Queue<any>()"
                    : parameter.Type is IRCommType { Kind: IRCommKind.Chan }
                        ? "new Channel<any>()"
                        : "new Stream<any>()"));
            sb.AppendLine($"void {task.Name}({arguments}).catch(error => {{");
            sb.AppendLine($"  setReportConnectionState('error', `Zadanie {EscapeStringLiteral(task.Name)}: ${{error instanceof Error ? error.message : String(error)}}`);");
            sb.AppendLine("});");
        }
        return new GeneratedFile("report", "report/browser.ts", sb.ToString());
    }

