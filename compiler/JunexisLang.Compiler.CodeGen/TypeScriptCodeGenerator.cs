    [ThreadStatic] private static IReadOnlyDictionary<string, IRSourceSpan>? _traceSourceMap;
    [ThreadStatic] private static TraceEmissionPolicy _tracePolicy;
    [ThreadStatic] private static string? _traceNarrativeId;
    [ThreadStatic] private static uint _traceTaskId;
    [ThreadStatic] private static string? _traceTaskName;

    private static void EmitTaskBoundaryTrace(
        StringBuilder sb,
        IRTask task,
        int globalTaskIndex,
        int reportTaskIndex)
    {
        if (_tracePolicy is TraceEmissionPolicy.Off ||
            string.IsNullOrWhiteSpace(_traceNarrativeId) ||
            _traceTaskId == 0)
        {
            return;
        }

        var source = globalTaskIndex >= 0
            ? TraceSourceForPath($"/Tasks[{globalTaskIndex}]")
            : null;
        var file = EscapeStringLiteral(source?.File ?? string.Empty);
        var line = source?.Line ?? 0;
        var functionName = EscapeStringLiteral(task.Name);
        var narrativeId = EscapeStringLiteral(_traceNarrativeId);
        var boundaryIndex = globalTaskIndex >= 0 ? globalTaskIndex : reportTaskIndex;

        if (boundaryIndex > 0)
        {
            sb.AppendLine(
                $"  await emitTrace('{TraceRuntimeContract.CommunicationReceive}', {_traceTaskId}, '{file}', {line}, '{functionName}', " +
                $"{{ {TraceRuntimeContract.NarrativeIdAttribute}: '{narrativeId}', {TraceRuntimeContract.PayloadHashAttribute}: 'startup-{boundaryIndex - 1}', {TraceRuntimeContract.PayloadTypeAttribute}: 'task-start' }});");
        }

        var payloadHash = $"startup-{boundaryIndex}";
        sb.AppendLine(
            $"  await emitTrace('{TraceRuntimeContract.CommunicationSend}', {_traceTaskId}, '{file}', {line}, '{functionName}', " +
            $"{{ {TraceRuntimeContract.NarrativeIdAttribute}: '{narrativeId}', {TraceRuntimeContract.PayloadHashAttribute}: '{payloadHash}', {TraceRuntimeContract.PayloadTypeAttribute}: 'task-start' }});");
    }

    private static bool EmitSendTrace(
        StringBuilder sb,
        string indent,
        IRType? outputType,
        string? sourcePath)
    {
        if (_tracePolicy is TraceEmissionPolicy.Off ||
            string.IsNullOrWhiteSpace(_traceNarrativeId) ||
            _traceTaskId == 0)
        {
            return false;
        }

        var source = sourcePath is not null ? TraceSourceForPath(sourcePath) : null;
        var file = EscapeStringLiteral(source?.File ?? string.Empty);
        var line = source?.Line ?? 0;
        var functionName = EscapeStringLiteral(_traceTaskName ?? string.Empty);
        var narrativeId = EscapeStringLiteral(_traceNarrativeId);
        var payloadType = EscapeStringLiteral(TracePayloadType(outputType));
        sb.AppendLine(
            $"{indent}await emitTrace('{TraceRuntimeContract.CommunicationSend}', {_traceTaskId}, '{file}', {line}, '{functionName}', " +
            $"{{ {TraceRuntimeContract.NarrativeIdAttribute}: '{narrativeId}', {TraceRuntimeContract.PayloadHashAttribute}: '{functionName}:{line}:' + String(Date.now()), {TraceRuntimeContract.PayloadTypeAttribute}: '{payloadType}' }});");
        return true;
    }

    private static void RepeatSourceMarkerAfterTrace(
        StringBuilder sb,
        string indent,
        string? sourcePath,
        bool traceEmitted)
    {
        if (traceEmitted && sourcePath is not null)
            sb.AppendLine($"{indent}// junexis:source {sourcePath}");
    }

    private static IRSourceSpan? TraceSourceForPath(string path)
    {
        if (_traceSourceMap is null)
            return null;

        if (_traceSourceMap.TryGetValue(path, out var exact))
            return exact;

        return _traceSourceMap
            .Where(entry => entry.Key.StartsWith(path, StringComparison.Ordinal))
            .OrderBy(entry => entry.Key.Length)
            .Select(entry => entry.Value)
            .FirstOrDefault();
    }

    private static string TracePayloadType(IRType? outputType) => outputType switch
    {
        IRCommType { Element: IRNamedType named } => named.Name,
        IRCommType { Element: var element } => TypeMappings.ToTypeScript(element),
        IRNamedType named => named.Name,
        null => "unknown",
        _ => TypeMappings.ToTypeScript(outputType),
    };

    private static void EmitStatements(
        StringBuilder sb,
        IReadOnlyList<IRStmt> statements,
        int indentLevel,
        IRType? outputType,
        IReadOnlyDictionary<string, IRType>? scope = null,
        Dictionary<string, QueueAckBinding>? ackBindings = null,
        string? sourcePathPrefix = null)
    {
        ackBindings ??= new Dictionary<string, QueueAckBinding>(StringComparer.Ordinal);
        for (var index = 0; index < statements.Count; index++)
            EmitStatement(sb, statements[index], indentLevel, outputType, scope, ackBindings,
                sourcePathPrefix is null ? null : $"{sourcePathPrefix}[{index}]");
    }

    private static bool UsesProducerTemplate(IRTask task) =>
        task.Params.Count == 0 &&
        task.Body.Count == 0 &&
        task.OutputType is IRCommType { Kind: IRCommKind.Chan };

