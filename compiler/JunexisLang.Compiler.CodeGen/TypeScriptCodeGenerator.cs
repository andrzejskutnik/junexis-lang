/// <summary>
/// Generuje TypeScript dla zadań z adnotacją <c>@report</c>.
/// Wyjście obejmuje runtime TypeScript oraz samodzielną aplikację przeglądarkową.
/// </summary>
public sealed class TypeScriptCodeGenerator : ICodeGenerator
{
    [ThreadStatic]
    private static HashSet<string>? _stateVariableNames;
    [ThreadStatic]
    private static string? _stateTaskName;

    /// <inheritdoc/>
    public string Platform => "report";

    /// <inheritdoc/>
    public IReadOnlyList<GeneratedFile> Generate(IRDocument ir, CodeGenOptions options)
    {
        var tasks = ir.Tasks
            .Where(t => t.Platforms.Any(p => p.Target == "report"))
            .ToList();

        if (tasks.Count == 0)
            return [];

        var anyNetworkChanBridgeForReport = ir.ChanBridges.Any(b => tasks.Any(t =>
            t.Params.Any(p => p.Name == b.TargetPort || b.TargetTask == t.Name))) ||
            tasks.Any(task => task.Params.Any(parameter =>
                parameter.Type is IRCommType { Kind: IRCommKind.Chan }));
        var needsMessagePack = anyNetworkChanBridgeForReport || ir.ChanBridges.Count > 0;
        var tracePolicy = TraceRuntimeContract.ResolvePolicy(ir.Narratives);
        var files = new List<GeneratedFile>
        {
            GenerateTypes(ir),
            GenerateRuntime(tracePolicy is not TraceEmissionPolicy.Off),
            GenerateIndex(ir, tasks, tracePolicy),
            GenerateDeployBootstrap(
                tasks,
                ir.ChanBridges.Count > 0 || ir.QueueBridges.Count > 0 || ir.StreamBridges.Count > 0),
            GenerateBrowserBootstrap(tasks),
            GenerateReportAdapterContract(),
            GenerateDefaultReportAdapter(),
            GenerateReportViewContract(),
            GenerateDefaultReportView(),
            GenerateReportView(),
            GenerateReportStyles(),
            GenerateReportHtml(tasks),
            GenerateReportManifest(tasks),
            GenerateReportServer(),
            GeneratePackageJson(needsMessagePack),
            GenerateTsConfig()
        };
        if (ExternContractManifestGenerator.Generate(ir, Platform) is { } externManifest)
            files.Add(externManifest);
        return files;
    }

