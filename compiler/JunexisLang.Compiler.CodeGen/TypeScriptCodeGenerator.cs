                sb.AppendLine($"  const result = undefined as unknown as {resultType};");

            if (UsesChanConsumerTemplate(task))
            {
                var inputName = task.Params[0].Name;
                var chanElementType = TypeMappings.ToTypeScript(((IRCommType)task.Params[0].Type).Element);
                if (taskProfile.SupportsNetworking)
                {
                    var chanBridge = ResolveChanBridgeDescriptor(ir, task, inputName);
                    sb.AppendLine($"  const __{inputName}ChanBridgeUrl = `${{junexisServerWsUrl}}{chanBridge.ChannelRoute}/ws`;");
                    sb.AppendLine($"  void bindChanBridgeConsumer<{chanElementType}>(__{inputName}ChanBridgeUrl, async payload => {{");
                    sb.AppendLine($"    consume{task.Name}Item(payload);");
                    sb.AppendLine("  }); // Auto-generated chan bridge bootstrap for report consumer");
                }
                sb.AppendLine($"  for await (const item of {inputName}) {{");
                sb.AppendLine($"    consume{task.Name}Item(item);");
                sb.AppendLine("  } // Auto-generated consumer template for single chan input");
            }
            else if (UsesStreamConsumerTemplate(task) && task.Params[0].Type is IRCommType { Element: var streamConsumerElement })
            {
                var inputName = task.Params[0].Name;
                var streamElementType = TypeMappings.ToTypeScript(streamConsumerElement);
                if (taskProfile.SupportsNetworking)
                {
                    var streamBridge = ResolveStreamBridgeDescriptor(ir, task, inputName);
                    sb.AppendLine($"  const __{inputName}StreamBridgeUrl = `${{junexisServerUrl}}{streamBridge.StreamRoute}`;");
                    sb.AppendLine($"  void bindStreamBridgeConsumer<{streamElementType}>(__{inputName}StreamBridgeUrl, async payload => {{");
                    sb.AppendLine($"    consume{task.Name}Item(payload);");
                    sb.AppendLine("  }); // Auto-generated stream bridge bootstrap for report consumer");
                }
            }
            else if (UsesQueueConsumerTemplate(task) && task.Params[0].Type is IRCommType { Element: var queueConsumerElement })
            {
                var inputName = task.Params[0].Name;
                var queueContract = QueueRuntimeContracts.ForTypeScript(queueConsumerElement);
                var queueElementType = TypeMappings.ToTypeScript(queueConsumerElement);
                if (taskProfile.SupportsNetworking)
                {
                    var queueBridge = ResolveQueueBridgeDescriptor(ir, task, inputName);
                    sb.AppendLine($"  const __{inputName}BridgeUrl = `${{junexisServerUrl}}{queueBridge.PollRoute}`;");
                    sb.AppendLine($"  const __{inputName}BridgeAckUrl = `${{junexisServerUrl}}{queueBridge.AckRoute}`;");
                    sb.AppendLine($"  void bindQueueBridgeConsumer<{queueElementType}>(__{inputName}BridgeUrl, __{inputName}BridgeAckUrl, async envelope => {{");
                    sb.AppendLine($"    consume{task.Name}Item(envelope.payload);");
                    sb.AppendLine("  }); // Auto-generated queue bridge bootstrap for report consumer");
                }
                sb.AppendLine("  while (true) {");
                sb.AppendLine($"    const [recvResult, messageId] = await {queueContract.RenderReceiveInvocation(inputName)};");
                sb.AppendLine("    if (!recvResult.ok || messageId === undefined) {");
                sb.AppendLine("      break;");
                sb.AppendLine("    }");
                sb.AppendLine("    try {");
                sb.AppendLine($"      consume{task.Name}Item(recvResult.value);");
                sb.AppendLine($"      await {queueContract.RenderAckInvocation(inputName, "messageId")};");
                sb.AppendLine("    } catch (error) {");
                sb.AppendLine("      // Runtime queue policy decides retry vs DLQ after nack.");
                sb.AppendLine($"      await {queueContract.RenderNackInvocation(inputName, "messageId", "error instanceof Error ? error.message : 'consume failed'")};");
                sb.AppendLine("    }");
                sb.AppendLine("  } // Auto-generated consumer template for single queue input");
            }

            var taskScope = task.Params.ToDictionary(p => p.Name, p => p.Type);
            var channelProducer = task.OutputType is IRCommType { Kind: IRCommKind.Chan } && task.Body.Count > 0;
            var bodyIndent = 1;
            if (channelProducer)
            {
                sb.AppendLine("  void (async () => {");
                bodyIndent = 2;
            }
            if (task.States.Count > 0)
            {
                var stateIndent = new string(' ', bodyIndent * 2);
                sb.AppendLine($"{stateIndent}const state = load{task.Name}State();");
                sb.AppendLine($"{stateIndent}try {{");
                bodyIndent++;
                _stateVariableNames = new HashSet<string>(task.States.Select(state => state.Name), StringComparer.Ordinal);
                _stateTaskName = task.Name;
            }

            EmitStatements(sb, task.Body, bodyIndent, task.OutputType, taskScope,
                sourcePathPrefix: taskIndex >= 0 ? $"/Tasks[{taskIndex}]/Body" : null);

            if (resultType is not null && !ContainsReturn(task.Body) && !channelProducer)
                sb.AppendLine($"{new string(' ', bodyIndent * 2)}return result;");

            if (task.States.Count > 0)
            {
                _stateVariableNames = null;
                _stateTaskName = null;
                bodyIndent--;
                var stateIndent = new string(' ', bodyIndent * 2);
                sb.AppendLine($"{stateIndent}}} finally {{");
                sb.AppendLine($"{stateIndent}  save{task.Name}State(state);");
                sb.AppendLine($"{stateIndent}}}");
            }

            if (channelProducer)
            {
                sb.AppendLine("    result.close();");
                sb.AppendLine("  })().catch(error => result.fail(error));");
                sb.AppendLine("  return result;");
            }

            sb.AppendLine($"}}");
            sb.AppendLine();

            if (task.States.Count > 0)
            {
                var stateCacheName = $"__{ToLocalIdentifier(task.Name)}StateCache";
                var stateStorageKey = $"junexis.state.{task.Name}";
                sb.AppendLine($"export const {task.Name}HasState = true;");
                sb.AppendLine($"type {task.Name}State = {{");
                foreach (var state in task.States)
                    sb.AppendLine($"  {state.Name}: {TypeMappings.ToTypeScript(state.Type)};");
                sb.AppendLine("};");
                sb.AppendLine();

                sb.AppendLine($"let {stateCacheName}: {task.Name}State | undefined;");
                sb.AppendLine();

                sb.AppendLine($"function createDefault{task.Name}State(): {task.Name}State {{");
                sb.AppendLine("  return {");
                foreach (var state in task.States)
                    sb.AppendLine($"    {state.Name}: {(state.Init is not null ? EmitExpr(state.Init) : EmitZeroValue(state.Type))},");
                sb.AppendLine("  };\n}");
                sb.AppendLine();

                sb.AppendLine($"function load{task.Name}State(): {task.Name}State {{");
                sb.AppendLine("  if (supportsLocalPersistence) {");
                sb.AppendLine($"    const persisted = localStorage.getItem('{EscapeStringLiteral(stateStorageKey)}');");
                sb.AppendLine("    if (persisted) {");
                sb.AppendLine("      try {");
                sb.AppendLine($"        const parsed = JSON.parse(persisted) as {task.Name}State;");
                sb.AppendLine($"        {stateCacheName} = {{ ...parsed }};");
                sb.AppendLine("      } catch {");
                sb.AppendLine("        // Ignore malformed persisted state and fall back to cache/default.");
                sb.AppendLine("      }");
                sb.AppendLine("    }");
                sb.AppendLine("  }");
                sb.AppendLine($"  return {stateCacheName} ? {{ ...{stateCacheName} }} : createDefault{task.Name}State();");
                sb.AppendLine("}");
                sb.AppendLine();

                sb.AppendLine($"function save{task.Name}State(state: {task.Name}State): void {{");
                sb.AppendLine($"  {stateCacheName} = {{ ...state }};");
                sb.AppendLine("  if (supportsLocalPersistence) {");
                sb.AppendLine($"    localStorage.setItem('{EscapeStringLiteral(stateStorageKey)}', JSON.stringify(state));");
                sb.AppendLine("  }");
                sb.AppendLine("}");
                sb.AppendLine();
            }

            if (UsesProducerTemplate(task) && task.OutputType is IRCommType { Kind: IRCommKind.Chan, Element: var producerElement })
            {
                sb.AppendLine($"function emit{task.Name}Value(): {TypeMappings.ToTypeScript(producerElement)} {{");
                sb.AppendLine($"  void {task.Name}PlatformProfile.supportsThreading;");
                sb.AppendLine($"  void {task.Name}PlatformProfile.supportsNetworking;");
                if (task.States.Count > 0)
                {
                    sb.AppendLine($"  if ({task.Name}HasState) {{");
                    sb.AppendLine($"    const state = load{task.Name}State();");
                    sb.AppendLine($"    return read{task.Name}StateValue(state);");
                    sb.AppendLine("  }");
                }
                sb.AppendLine($"  return {EmitZeroValue(producerElement)};");
                sb.AppendLine("}");
                sb.AppendLine();
            }

            if ((UsesChanConsumerTemplate(task) || UsesQueueConsumerTemplate(task) || UsesStreamConsumerTemplate(task)) && task.Params[0].Type is IRCommType { Element: var consumerElement })
            {
                sb.AppendLine($"function consume{task.Name}Item(item: {TypeMappings.ToTypeScript(consumerElement)}): void {{");
                sb.AppendLine($"  void {task.Name}PlatformProfile.supportsThreading;");
                sb.AppendLine($"  void {task.Name}PlatformProfile.supportsNetworking;");
                if (task.States.Count > 0)
                {
                    sb.AppendLine($"  if ({task.Name}HasState) {{");
                    sb.AppendLine($"    const state = load{task.Name}State();");
                    sb.AppendLine($"    write{task.Name}StateValue(state, item);");
                    sb.AppendLine($"    save{task.Name}State(state);");
                    sb.AppendLine("  }");
                }
                sb.AppendLine("  console.log(item);");
                sb.AppendLine($"  renderReportItem('{EscapeStringLiteral(task.Name)}', item);");
                sb.AppendLine("}");
                sb.AppendLine();
            }

            if (task.States.Count > 0 && UsesProducerTemplate(task) && task.OutputType is IRCommType { Kind: IRCommKind.Chan, Element: var readElement })
            {
                var matchingStates = StateAccessPlanner.GetReadPreferredCompatibleStates(task, readElement, TypeMappings.ToTypeScript);
                sb.AppendLine($"function read{task.Name}StateValue(state: {task.Name}State): {TypeMappings.ToTypeScript(readElement)} {{");
                if (matchingStates.Count > 0)
                {
                    if (matchingStates.Count > 1)
                        sb.AppendLine($"  // Candidate state fields: {string.Join(", ", matchingStates.Select(state => state.Name))}");
                    sb.AppendLine($"  return state.{matchingStates[0].Name};");
                }
                else
                {
                    sb.AppendLine("  void state;");
                    sb.AppendLine($"  return {EmitZeroValue(readElement)};");
                }
                sb.AppendLine("}");
                sb.AppendLine();
            }

            if (task.States.Count > 0 && (UsesChanConsumerTemplate(task) || UsesQueueConsumerTemplate(task)) && task.Params[0].Type is IRCommType { Element: var writeElement })
            {
                var matchingStates = StateAccessPlanner.GetWritePreferredCompatibleStates(task, writeElement, TypeMappings.ToTypeScript);
                sb.AppendLine($"function write{task.Name}StateValue(state: {task.Name}State, item: {TypeMappings.ToTypeScript(writeElement)}): void {{");
                if (matchingStates.Count > 0)
                {
                    if (matchingStates.Count > 1)
                        sb.AppendLine($"  // Candidate state fields: {string.Join(", ", matchingStates.Select(state => state.Name))}");
                    foreach (var matchingState in matchingStates)
                        sb.AppendLine($"  state.{matchingState.Name} = item;");
                    sb.AppendLine($"  void state.{matchingStates[0].Name};");
                }
                else
                {
                    sb.AppendLine("  void state;");
                    sb.AppendLine("  void item;");
                }
                sb.AppendLine("}");
                sb.AppendLine();
            }
        }

        _traceSourceMap = null;
        _tracePolicy = TraceEmissionPolicy.Off;
        _traceNarrativeId = null;
        _traceTaskId = 0;
        _traceTaskName = null;
        return new GeneratedFile("report", "report/index.ts", sb.ToString());
    }

    private static IReadOnlyList<IRExternTask> CollectExternalCalls(IRDocument ir, IReadOnlyList<IRTask> tasks)
    {
        var declared = ir.Structs.Select(structure => structure.Name)
            .Concat(ir.Enums.Select(@enum => @enum.Name))
            .Concat(tasks.Select(task => task.Name))
            .Append("__array__")
            .Append("__json__")
            .Append("now")
            .Append("epoch")
            .ToHashSet(StringComparer.Ordinal);
        var calls = new HashSet<string>(StringComparer.Ordinal);

        foreach (var task in tasks)
        {
            foreach (var state in task.States)
                if (state.Init is not null) CollectCalls(state.Init, calls);
            if (task.Config is not null)
                foreach (var field in task.Config.Fields)
                    if (field.Default is not null) CollectCalls(field.Default, calls);
            CollectCalls(task.Body, calls);
            foreach (var hook in task.Hooks)
                CollectCalls(hook.Body, calls);
        }

        calls.ExceptWith(declared);
        var reportExterns = ir.ExternTasks
            .Where(external => external.Platforms.Any(platform => platform.Target == "report"))
            .ToDictionary(external => external.Name, StringComparer.Ordinal);
        return calls
            .Where(reportExterns.ContainsKey)
            .OrderBy(name => name, StringComparer.Ordinal)
            .Select(name => reportExterns[name])
            .ToList();
    }

    private static void CollectCalls(IEnumerable<IRStmt> statements, ISet<string> calls)
    {
        foreach (var statement in statements)
        {
            switch (statement)
            {
                case IRLetStmt let: CollectCalls(let.Init, calls); break;
                case IRReturnStmt { Value: not null } @return: CollectCalls(@return.Value, calls); break;
                case IRDelayStmt delay: CollectCalls(delay.Duration, calls); break;
                case IRLogStmt log:
                    foreach (var argument in log.Args) CollectCalls(argument, calls);
                    break;
                case IRSendStmt send:
                    CollectCalls(send.Value, calls);
                    if (send.Target is not null) CollectCalls(send.Target, calls);
                    break;
                case IRRecvStmt receive: CollectCalls(receive.Source, calls); break;
                case IRRespondStmt respond: CollectCalls(respond.Value, calls); break;
                case IRExprStmt expression: CollectCalls(expression.Expr, calls); break;
                case IRIfStmt conditional:
                    CollectCalls(conditional.Condition, calls);
                    CollectCalls(conditional.Then, calls);
                    if (conditional.Else is IRElseIf elseIf) CollectCalls([elseIf.IfStmt], calls);
                    if (conditional.Else is IRElseBlock elseBlock) CollectCalls(elseBlock.Body, calls);
                    break;
                case IRForStmt loop:
                    CollectCalls(loop.Iter, calls);
                    CollectCalls(loop.Body, calls);
                    break;
                case IREveryStmt every:
                    CollectCalls(every.Interval, calls);
                    CollectCalls(every.Body, calls);
                    break;
                case IRLoopStmt loop: CollectCalls(loop.Body, calls); break;
                case IRMatchStmt match:
                    CollectCalls(match.Subject, calls);
                    foreach (var arm in match.Arms)
                    {
                        CollectCalls(arm.Body, calls);
                        if (arm.BodyExpr is not null) CollectCalls(arm.BodyExpr, calls);
                    }
                    break;
            }
        }
    }

    private static void CollectCalls(IRExpr expression, ISet<string> calls)
    {
        switch (expression)
        {
            case IRCallExpr call:
                if (call.Callee is IRIdentExpr identifier) calls.Add(identifier.Name);
                else CollectCalls(call.Callee, calls);
                foreach (var argument in call.Args) CollectCalls(argument.Value, calls);
                break;
            case IRBinaryExpr binary:
                CollectCalls(binary.Left, calls);
                CollectCalls(binary.Right, calls);
                break;
            case IRUnaryExpr unary: CollectCalls(unary.Operand, calls); break;
            case IRFieldAccessExpr field: CollectCalls(field.Object, calls); break;
            case IRIndexExpr index:
                CollectCalls(index.Object, calls);
                CollectCalls(index.Index, calls);
                break;
            case IRTernaryExpr ternary:
                CollectCalls(ternary.Cond, calls);
                CollectCalls(ternary.Then, calls);
                CollectCalls(ternary.Else, calls);
                break;
            case IRClosureExpr closure: CollectCalls(closure.Body, calls); break;
            case IRSendExpr send:
                CollectCalls(send.Value, calls);
                if (send.Target is not null) CollectCalls(send.Target, calls);
                break;
            case IRRecvExpr receive: CollectCalls(receive.Source, calls); break;
            case IRAwaitExpr awaitExpression: CollectCalls(awaitExpression.Inner, calls); break;
        }
    }

    private static void EmitPlatformHelpers(StringBuilder sb, Core.Platform.PlatformCapabilities profile, bool anyStorageBackedState, bool anyNetworkQueueBridge, bool anyNetworkStreamBridge, bool anyNetworkChanBridge)
    {
        if (profile.SupportsThreading)
        {
            sb.AppendLine("function initializePlatformThreading(): void {");
            sb.AppendLine("  // Threading bootstrap enabled by platform profile.");
            sb.AppendLine("  void supportsWorkers;");
            sb.AppendLine("}");
            sb.AppendLine();
        }

        if (profile.SupportsNetworking)
        {
            if (anyNetworkQueueBridge || anyNetworkStreamBridge || anyNetworkChanBridge)
            {
                sb.AppendLine($"const JUNEXIS_WIRE_VERSION = '{WireRuntimeContractCatalog.Json.Version}' as const;");
                sb.AppendLine();
            }
            sb.AppendLine("function initializePlatformNetworking(): void {");
            sb.AppendLine("  // Networking bootstrap enabled by platform profile.");
            sb.AppendLine("  void supportsFetch;");
            sb.AppendLine("}");
            sb.AppendLine();

            if (anyNetworkQueueBridge)
            {
                sb.AppendLine("type QueueBridgeEnvelope<T> = {");
                sb.AppendLine("  version: typeof JUNEXIS_WIRE_VERSION;");
                sb.AppendLine("  messageId: string;");
                sb.AppendLine("  payload: T;");
                sb.AppendLine("};");
                sb.AppendLine();
                sb.AppendLine("type QueueAckFrame = {");
                sb.AppendLine("  kind: 'ack' | 'nack';");
                sb.AppendLine("  messageId: string;");
                sb.AppendLine("  reason?: string;");
                sb.AppendLine("};");
                sb.AppendLine();
                sb.AppendLine("function createQueueAckFrame(messageId: string): QueueAckFrame {");
                sb.AppendLine("  return { kind: 'ack', messageId };");
                sb.AppendLine("}");
                sb.AppendLine();
                sb.AppendLine("function createQueueNackFrame(messageId: string, reason: string): QueueAckFrame {");
                sb.AppendLine("  return { kind: 'nack', messageId, reason };");
                sb.AppendLine("}");
                sb.AppendLine();
                sb.AppendLine("export function parseQueueBridgeEnvelope<T>(data: string): QueueBridgeEnvelope<T> {");
                sb.AppendLine("  const envelope = JSON.parse(data) as QueueBridgeEnvelope<T>;");
                sb.AppendLine("  if (envelope.version !== JUNEXIS_WIRE_VERSION) throw new Error(`unsupported Junexis wire version: ${envelope.version}`);");
                sb.AppendLine("  return envelope;");
                sb.AppendLine("}");
                sb.AppendLine();
                sb.AppendLine("async function sendQueueBridgeAck(url: string, messageId: string): Promise<void> {");
                sb.AppendLine("  await postQueueBridgeFrame(url, createQueueAckFrame(messageId));");
                sb.AppendLine("}");
                sb.AppendLine();
                sb.AppendLine("async function sendQueueBridgeNack(url: string, messageId: string, reason: string): Promise<void> {");
                sb.AppendLine("  await postQueueBridgeFrame(url, createQueueNackFrame(messageId, reason));");
                sb.AppendLine("}");
                sb.AppendLine();
                sb.AppendLine("async function postQueueBridgeFrame(url: string, frame: QueueAckFrame): Promise<void> {");
                sb.AppendLine("  const response = await fetch(url, {");
                sb.AppendLine("    method: 'POST',");
                sb.AppendLine("    headers: { 'Content-Type': 'application/json' },");
                sb.AppendLine("    body: JSON.stringify(frame)");
                sb.AppendLine("  });");
                sb.AppendLine("  if (!response.ok && response.status !== 204) {");
                sb.AppendLine("    throw new Error(`queue bridge ACK failed: ${response.status}`);");
                sb.AppendLine("  }");
                sb.AppendLine("}");
                sb.AppendLine();
                sb.AppendLine("export async function pollQueueBridge<T>(url: string): Promise<QueueBridgeEnvelope<T> | undefined> {");
                sb.AppendLine("  const response = await fetch(url);");
                sb.AppendLine("  if (response.status === 204) {");
                sb.AppendLine("    return undefined;");
                sb.AppendLine("  }");
                sb.AppendLine("  if (!response.ok) {");
                sb.AppendLine("    throw new Error(`queue bridge poll failed: ${response.status}`);");
                sb.AppendLine("  }");
                sb.AppendLine("  return parseQueueBridgeEnvelope<T>(await response.text());");
                sb.AppendLine("}");
                sb.AppendLine();
                sb.AppendLine("async function bindQueueBridgeConsumer<T>(pollUrl: string, ackUrl: string, handleEnvelope: (envelope: QueueBridgeEnvelope<T>) => Promise<void>): Promise<void> {");
                sb.AppendLine("  while (true) {");
                sb.AppendLine("    const envelope = await pollQueueBridge<T>(pollUrl);");
                sb.AppendLine("    if (!envelope) {");
                sb.AppendLine("      break;");
                sb.AppendLine("    }");
                sb.AppendLine("    try {");
                sb.AppendLine("      await handleEnvelope(envelope);");
                sb.AppendLine("      await sendQueueBridgeAck(ackUrl, envelope.messageId);");
                sb.AppendLine("    } catch (error) {");
                sb.AppendLine("      await sendQueueBridgeNack(ackUrl, envelope.messageId, error instanceof Error ? error.message : 'bridge handler failed');");
                sb.AppendLine("    }");
                sb.AppendLine("  }");
                sb.AppendLine("}");
                sb.AppendLine();
            }

            if (anyNetworkStreamBridge)
            {
                sb.AppendLine("type StreamBridgeEnvelope<T> = {");
                sb.AppendLine("  version: typeof JUNEXIS_WIRE_VERSION;");
                sb.AppendLine("  payload: T;");
                sb.AppendLine("};");
                sb.AppendLine();
                sb.AppendLine("export function parseStreamBridgeEnvelope<T>(data: string): StreamBridgeEnvelope<T> {");
                sb.AppendLine("  const envelope = JSON.parse(data) as StreamBridgeEnvelope<T>;");
                sb.AppendLine("  if (envelope.version !== JUNEXIS_WIRE_VERSION) throw new Error(`unsupported Junexis wire version: ${envelope.version}`);");
                sb.AppendLine("  return envelope;");
                sb.AppendLine("}");
                sb.AppendLine();
                sb.AppendLine("export async function pollStreamBridge<T>(url: string): Promise<StreamBridgeEnvelope<T> | undefined> {");
                sb.AppendLine("  const response = await fetch(url);");
                sb.AppendLine("  if (response.status === 204) {");
                sb.AppendLine("    return undefined;");
                sb.AppendLine("  }");
                sb.AppendLine("  if (!response.ok) {");
                sb.AppendLine("    throw new Error(`stream bridge poll failed: ${response.status}`);");
                sb.AppendLine("  }");
                sb.AppendLine("  return parseStreamBridgeEnvelope<T>(await response.text());");
                sb.AppendLine("}");
                sb.AppendLine();
                sb.AppendLine("async function bindStreamBridgeConsumer<T>(pollUrl: string, handlePayload: (payload: T) => Promise<void>): Promise<void> {");
                sb.AppendLine("  while (true) {");
                sb.AppendLine("    const envelope = await pollStreamBridge<T>(pollUrl);");
                sb.AppendLine("    if (!envelope) {");
                sb.AppendLine("      break;");
                sb.AppendLine("    }");
                sb.AppendLine("    await handlePayload(envelope.payload);");
                sb.AppendLine("  }");
                sb.AppendLine("}");
                sb.AppendLine();
            }

            if (anyNetworkChanBridge)
            {
                sb.AppendLine("// bindChanBridgeConsumer — connects via WebSocket, decodes MessagePack binary frames,");
                sb.AppendLine("// and reconnects automatically with exponential backoff (1s→2s→4s→…→30s).");
                sb.AppendLine("// Requires @msgpack/msgpack: npm install @msgpack/msgpack");
                sb.AppendLine("import { decode as msgpackDecode } from '@msgpack/msgpack';");
                sb.AppendLine();
                sb.AppendLine("const RECONNECT_BACKOFF_INITIAL_MS = 1_000;");
                sb.AppendLine("const RECONNECT_BACKOFF_MAX_MS    = 30_000;");
                sb.AppendLine();
                sb.AppendLine("function bindChanBridgeConsumer<T>(wsUrl: string, handlePayload: (payload: T) => Promise<void>): void {");
                sb.AppendLine("  let backoffMs = RECONNECT_BACKOFF_INITIAL_MS;");
                sb.AppendLine("  let shuttingDown = false;");
                sb.AppendLine("  setReportConnectionState('connecting');");
                sb.AppendLine();
                sb.AppendLine("  function connect(): void {");
                sb.AppendLine("    const ws = new WebSocket(wsUrl);");
                sb.AppendLine("    ws.binaryType = 'arraybuffer';");
                sb.AppendLine();
                sb.AppendLine("    ws.onopen = () => {");
                sb.AppendLine("      console.log(`[bridge] connected to ${wsUrl}`);");
                sb.AppendLine("      setReportConnectionState('connected');");
                sb.AppendLine("      backoffMs = RECONNECT_BACKOFF_INITIAL_MS; // reset on successful connect");
                sb.AppendLine("    };");
                sb.AppendLine();
                sb.AppendLine("    ws.onmessage = async (event: MessageEvent) => {");
                sb.AppendLine("      try {");
                sb.AppendLine("        // Check for text control frames (e.g. graceful shutdown notification)");
                sb.AppendLine("        if (typeof event.data === 'string') {");
                sb.AppendLine("          try {");
                sb.AppendLine("            const ctrl = JSON.parse(event.data as string) as { type?: string; reason?: string };");
                sb.AppendLine("            if (ctrl.type === 'shutdown') {");
                sb.AppendLine("              console.log(`[bridge] server shutdown: ${ctrl.reason ?? 'no reason given'}`);");
                sb.AppendLine("              shuttingDown = false; // allow reconnect after shutdown");
                sb.AppendLine("              return;");
                sb.AppendLine("            }");
                sb.AppendLine("          } catch { /* not JSON — ignore */ }");
                sb.AppendLine("          return;");
                sb.AppendLine("        }");
                sb.AppendLine("        const payload = msgpackDecode(new Uint8Array(event.data as ArrayBuffer)) as T;");
                sb.AppendLine("        await handlePayload(payload);");
                sb.AppendLine("      } catch (err) {");
                sb.AppendLine("        console.error('[bridge] message handling error:', err);");
                sb.AppendLine("      }");
                sb.AppendLine("    };");
                sb.AppendLine();
                sb.AppendLine("    ws.onerror = (err: Event) => {");
                sb.AppendLine("      console.warn('[bridge] WebSocket error:', err);");
                sb.AppendLine("      setReportConnectionState('error', 'Błąd połączenia z serwerem.');");
                sb.AppendLine("    };");
                sb.AppendLine();
                sb.AppendLine("    ws.onclose = () => {");
                sb.AppendLine("      if (shuttingDown) return;");
                sb.AppendLine("      console.log(`[bridge] disconnected, reconnecting in ${backoffMs}ms…`);");
                sb.AppendLine("      setReportConnectionState('reconnecting', `Połączenie przerwane — ponowienie za ${backoffMs} ms.`);");
                sb.AppendLine("      setTimeout(() => {");
                sb.AppendLine("        connect();");
                sb.AppendLine("        backoffMs = Math.min(backoffMs * 2, RECONNECT_BACKOFF_MAX_MS);");
                sb.AppendLine("      }, backoffMs);");
                sb.AppendLine("    };");
                sb.AppendLine("  }");
                sb.AppendLine();
                sb.AppendLine("  connect();");
                sb.AppendLine("}");
                sb.AppendLine();
            }
        }

        if (profile.SupportsFileIO || anyStorageBackedState)
        {
            sb.AppendLine("function initializePlatformFileIO(): void {");
            sb.AppendLine("  // File I/O bootstrap enabled by platform profile.");
            sb.AppendLine("  void supportsLocalPersistence;");
            sb.AppendLine("}");
        }
    }

