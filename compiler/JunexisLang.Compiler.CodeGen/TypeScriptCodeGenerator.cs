        task.Params.Count == 1 &&
        task.Body.Count == 0 &&
        task.OutputType is null &&
        task.Params[0].Type is IRCommType { Kind: IRCommKind.Chan };

    private static bool UsesQueueConsumerTemplate(IRTask task) =>
        task.Params.Count == 1 &&
        task.Body.Count == 0 &&
        task.OutputType is null &&
        task.Params[0].Type is IRCommType { Kind: IRCommKind.Queue };

    private static bool UsesStreamConsumerTemplate(IRTask task) =>
        task.Params.Count == 1 &&
        task.Body.Count == 0 &&
        task.OutputType is null &&
        task.Params[0].Type is IRCommType { Kind: IRCommKind.Stream };

    private static void EmitStatement(
        StringBuilder sb,
        IRStmt statement,
        int indentLevel,
        IRType? outputType,
        IReadOnlyDictionary<string, IRType>? scope = null,
        Dictionary<string, QueueAckBinding>? ackBindings = null,
        string? sourcePath = null)
    {
        var indent = new string(' ', indentLevel * 2);
        ackBindings ??= new Dictionary<string, QueueAckBinding>(StringComparer.Ordinal);
        var traceBeforeStatement = statement is IRSendStmt &&
            _tracePolicy is not TraceEmissionPolicy.Off &&
            !string.IsNullOrWhiteSpace(_traceNarrativeId) &&
            _traceTaskId != 0;
        if (sourcePath is not null && !traceBeforeStatement)
            sb.AppendLine($"{indent}// junexis:source {sourcePath}");

        switch (statement)
        {
            case IRLetStmt letStmt:
            {
                if (TryEmitQueueReceiveLet(sb, indent, letStmt, scope, ackBindings))
                    break;

                var keyword = letStmt.Kind.Equals("const", StringComparison.OrdinalIgnoreCase) ? "const" : "let";
                var typeAnnotation = letStmt.Type is not null ? $": {TypeMappings.ToTypeScript(letStmt.Type)}" : string.Empty;
                sb.AppendLine($"{indent}{keyword} {letStmt.Name}{typeAnnotation} = {EmitExpr(letStmt.Init)};");
                break;
            }

            case IRLogStmt logStmt:
                sb.AppendLine($"{indent}console.log({string.Join(", ", logStmt.Args.Select(EmitExpr))});");
                break;

            case IRExprStmt exprStmt:
                if (exprStmt.Expr is IRBinaryExpr binaryExpr && IsAssignmentOperator(binaryExpr.Op))
                {
                    sb.AppendLine($"{indent}{EmitExpr(binaryExpr.Left)} {binaryExpr.Op} {EmitExpr(binaryExpr.Right)};");
                }
                else
                {
                    sb.AppendLine($"{indent}{EmitExpr(exprStmt.Expr)};");
                }
                break;

            case IRReturnStmt returnStmt:
                sb.AppendLine(returnStmt.Value is not null
                    ? $"{indent}return {EmitExpr(returnStmt.Value)};"
                    : $"{indent}return;");
                break;

            case IRIfStmt ifStmt:
                EmitIfStatement(sb, ifStmt, indentLevel, outputType, scope, ackBindings, sourcePath);
                break;

            case IREveryStmt everyStmt:
                sb.AppendLine($"{indent}const _interval = setInterval(async () => {{");
                EmitStatements(sb, everyStmt.Body, indentLevel + 1, outputType, scope,
                    new Dictionary<string, QueueAckBinding>(ackBindings), sourcePath is null ? null : $"{sourcePath}/Body");
                if (_stateVariableNames is not null && _stateTaskName is not null)
                    sb.AppendLine($"{indent}  save{_stateTaskName}State(state);");
                sb.AppendLine($"{indent}}}, {EmitDuration(everyStmt.Interval)});");
                sb.AppendLine($"{indent}void _interval;");
                sb.AppendLine($"{indent}void junexis;");
                break;

            case IRLoopStmt loopStmt:
                sb.AppendLine($"{indent}while (true) {{");
                EmitStatements(sb, loopStmt.Body, indentLevel + 1, outputType, scope,
                    new Dictionary<string, QueueAckBinding>(ackBindings), sourcePath is null ? null : $"{sourcePath}/Body");
                sb.AppendLine($"{indent}}}");
                break;

            case IRForStmt forStmt:
                sb.AppendLine($"{indent}for await (const {forStmt.Var} of {EmitExpr(forStmt.Iter)}) {{");
                EmitStatements(sb, forStmt.Body, indentLevel + 1, outputType, scope,
                    new Dictionary<string, QueueAckBinding>(ackBindings), sourcePath is null ? null : $"{sourcePath}/Body");
                sb.AppendLine($"{indent}}}");
                break;

            case IRMatchStmt matchStmt:
                EmitMatchStatement(sb, matchStmt, indentLevel, outputType, scope, ackBindings, sourcePath);
                break;

            case IRAckStmt ackStmt:
                EmitQueueAckNack(sb, indent, "ack", ackStmt.Message, null, ackBindings);
                break;

            case IRNackStmt nackStmt:
                EmitQueueAckNack(sb, indent, "nack", nackStmt.Message, nackStmt.Reason, ackBindings);
                break;

            case IRSendStmt sendStmt:
                var traceEmitted = EmitSendTrace(sb, indent, outputType, sourcePath);
                RepeatSourceMarkerAfterTrace(sb, indent, sourcePath, traceEmitted);
                if (sendStmt.Target is not null)
                {
                    sb.AppendLine($"{indent}await junexis.send({EmitExpr(sendStmt.Target)}, {EmitExpr(sendStmt.Value)});");
                }
                else if (outputType is IRCommType { Kind: IRCommKind.Chan })
                {
                    var chanContract = ChanRuntimeContracts.ForTypeScript(((IRCommType)outputType).Element);
                    sb.AppendLine($"{indent}await {chanContract.RenderSendInvocation("result", EmitExpr(sendStmt.Value))};");
                }
                else if (outputType is IRCommType { Kind: IRCommKind.Queue })
                {
                    sb.AppendLine($"{indent}result.enqueue({EmitExpr(sendStmt.Value)});");
                }
                else if (outputType is IRCommType { Kind: IRCommKind.Stream })
                {
                    var streamContract = StreamRuntimeContracts.ForTypeScript(((IRCommType)outputType).Element);
                    sb.AppendLine($"{indent}{streamContract.RenderPublishInvocation("result", EmitExpr(sendStmt.Value))};");
                }
                else if (outputType is not null)
                {
                    sb.AppendLine($"{indent}result = {EmitExpr(sendStmt.Value)};");
                }
                else
                {
                    sb.AppendLine($"{indent}// send: no output type declared for this task");
                }
                break;

            default:
                throw new NotSupportedException($"TypeScript codegen does not support statement {statement.GetType().Name}.");
        }
    }

    private static bool TryEmitQueueReceiveLet(
        StringBuilder sb,
        string indent,
        IRLetStmt letStmt,
        IReadOnlyDictionary<string, IRType>? scope,
        Dictionary<string, QueueAckBinding> ackBindings)
    {
        if (letStmt.Init is not IRRecvExpr { Source: IRIdentExpr { Name: var sourceName } recvSource })
            return false;

        if (scope is null ||
            !scope.TryGetValue(sourceName, out var sourceType) ||
            sourceType is not IRCommType { Kind: IRCommKind.Queue })
            return false;

        var queueExpr = EmitExpr(recvSource);
        var frameVar = $"__{letStmt.Name}Frame";
        var keyword = letStmt.Kind.Equals("const", StringComparison.OrdinalIgnoreCase) ? "const" : "let";
        sb.AppendLine($"{indent}const {frameVar} = await {queueExpr}.recv();");
        sb.AppendLine($"{indent}if ({frameVar} === undefined) {{ return; }}");
        sb.AppendLine($"{indent}{keyword} {letStmt.Name} = {frameVar}.value;");
        ackBindings[letStmt.Name] = new QueueAckBinding(queueExpr, $"{frameVar}.messageId");
        return true;
    }

    private static void EmitQueueAckNack(
        StringBuilder sb,
        string indent,
        string method,
        IRExpr message,
        IRExpr? reason,
        IReadOnlyDictionary<string, QueueAckBinding> ackBindings)
    {
        if (message is IRIdentExpr { Name: var name } &&
            ackBindings.TryGetValue(name, out var binding))
        {
            if (method == "ack")
            {
                sb.AppendLine($"{indent}{binding.QueueExpr}.ack({binding.MessageIdExpr});");
            }
            else
            {
                var reasonExpr = reason is not null ? EmitExpr(reason) : "'nack'";
                sb.AppendLine($"{indent}{binding.QueueExpr}.nack({binding.MessageIdExpr}, {reasonExpr});");
            }
            return;
        }

        sb.AppendLine($"{indent}// {method}: target is not bound to a queue receive in codegen");
    }

    private static string EmitExpr(IRExpr expr) => expr switch
    {
        IRLiteralExpr literalExpr => EmitValue(literalExpr.Value),
        IRIdentExpr identExpr => _stateVariableNames?.Contains(identExpr.Name) == true
            ? $"state.{identExpr.Name}"
            : identExpr.Name,
        IRConfigAccessExpr configAccessExpr => configAccessExpr.Field is not null ? $"config.{configAccessExpr.Field}" : "config",
        IRBinaryExpr { Op: "as", Right: IRIdentExpr targetType } castExpr => EmitCast(castExpr.Left, targetType.Name),
        IRBinaryExpr binaryExpr => $"({EmitExpr(binaryExpr.Left)} {MapBinaryOperator(binaryExpr.Op)} {EmitExpr(binaryExpr.Right)})",
        IRUnaryExpr unaryExpr => $"({MapUnaryOperator(unaryExpr.Op)}{EmitExpr(unaryExpr.Operand)})",
        IRCallExpr callExpr => EmitCall(callExpr),
        IRFieldAccessExpr fieldAccessExpr => $"{EmitExpr(fieldAccessExpr.Object)}.{fieldAccessExpr.Field}",
        IRIndexExpr indexExpr => $"{EmitExpr(indexExpr.Object)}[{EmitExpr(indexExpr.Index)}]",
        IREnumAccessExpr enumAccessExpr => $"{{ kind: '{enumAccessExpr.Variant}' }}",
        IRTernaryExpr ternaryExpr => $"({EmitExpr(ternaryExpr.Cond)} ? {EmitExpr(ternaryExpr.Then)} : {EmitExpr(ternaryExpr.Else)})",
        IRRecvExpr recvExpr => $"await {EmitExpr(recvExpr.Source)}[Symbol.asyncIterator]().next()",
        IRSendExpr sendExpr => sendExpr.Target is not null
            ? $"await junexis.send({EmitExpr(sendExpr.Target)}, {EmitExpr(sendExpr.Value)})"
            : EmitExpr(sendExpr.Value),
        IRAwaitExpr awaitExpr => $"await {EmitExpr(awaitExpr.Inner)}",
        _ => throw new NotSupportedException($"TypeScript codegen does not support expression {expr.GetType().Name}.")
    };

    private static string MapBinaryOperator(string op) => op switch
    {
        "and" => "&&",
        "or" => "||",
        _ => op,
    };

    private static string MapUnaryOperator(string op) => op switch
    {
        "not" => "!",
        _ => op,
    };

    private static bool IsAssignmentOperator(string op) => op is "=" or "+=" or "-=" or "*=" or "/=" or "%=";

    private static string EmitCast(IRExpr value, string targetType)
    {
        var emittedValue = EmitExpr(value);
        return targetType switch
        {
            "Int" => $"Number({emittedValue})",
            "Float" => $"Number({emittedValue})",
            "Bool" => $"Boolean({emittedValue})",
            "Text" => $"String({emittedValue})",
            _ => $"({emittedValue} as {targetType})",
        };
    }

    private static void EmitIfStatement(
        StringBuilder sb,
        IRIfStmt ifStmt,
        int indentLevel,
        IRType? outputType,
        IReadOnlyDictionary<string, IRType>? scope = null,
        Dictionary<string, QueueAckBinding>? ackBindings = null,
        string? sourcePath = null)
    {
        ackBindings ??= new Dictionary<string, QueueAckBinding>(StringComparer.Ordinal);
        var indent = new string(' ', indentLevel * 2);
        sb.AppendLine($"{indent}if ({EmitExpr(ifStmt.Condition)}) {{");
        EmitStatements(sb, ifStmt.Then, indentLevel + 1, outputType, scope,
            new Dictionary<string, QueueAckBinding>(ackBindings), sourcePath is null ? null : $"{sourcePath}/Then");

        switch (ifStmt.Else)
        {
            case IRElseIf elseIf:
                EmitElseIfClause(sb, elseIf.IfStmt, indentLevel, outputType, scope, ackBindings,
                    sourcePath is null ? null : $"{sourcePath}/Else");
                return;

            case IRElseBlock elseBlock:
                sb.AppendLine($"{indent}}} else {{");
                EmitStatements(sb, elseBlock.Body, indentLevel + 1, outputType, scope,
                    new Dictionary<string, QueueAckBinding>(ackBindings), sourcePath is null ? null : $"{sourcePath}/Else/Body");
                break;
        }

        sb.AppendLine($"{indent}}}");
    }

    private static void EmitElseIfClause(
        StringBuilder sb,
        IRIfStmt ifStmt,
        int indentLevel,
        IRType? outputType,
        IReadOnlyDictionary<string, IRType>? scope = null,
        Dictionary<string, QueueAckBinding>? ackBindings = null,
        string? sourcePath = null)
    {
        ackBindings ??= new Dictionary<string, QueueAckBinding>(StringComparer.Ordinal);
        var indent = new string(' ', indentLevel * 2);
        sb.AppendLine($"{indent}}} else if ({EmitExpr(ifStmt.Condition)}) {{");
        EmitStatements(sb, ifStmt.Then, indentLevel + 1, outputType, scope,
            new Dictionary<string, QueueAckBinding>(ackBindings), sourcePath is null ? null : $"{sourcePath}/Then");

        switch (ifStmt.Else)
        {
            case IRElseIf nestedElseIf:
                EmitElseIfClause(sb, nestedElseIf.IfStmt, indentLevel, outputType, scope, ackBindings,
                    sourcePath is null ? null : $"{sourcePath}/Else");
                return;

            case IRElseBlock elseBlock:
                sb.AppendLine($"{indent}}} else {{");
                EmitStatements(sb, elseBlock.Body, indentLevel + 1, outputType, scope,
                    new Dictionary<string, QueueAckBinding>(ackBindings), sourcePath is null ? null : $"{sourcePath}/Else/Body");
                break;
        }

        sb.AppendLine($"{indent}}}");
    }

    private static void EmitMatchStatement(
        StringBuilder sb,
        IRMatchStmt matchStmt,
        int indentLevel,
        IRType? outputType,
        IReadOnlyDictionary<string, IRType>? scope = null,
        Dictionary<string, QueueAckBinding>? ackBindings = null,
        string? sourcePath = null)
    {
        ackBindings ??= new Dictionary<string, QueueAckBinding>(StringComparer.Ordinal);
        var indent = new string(' ', indentLevel * 2);
        sb.AppendLine($"{indent}{{");
        sb.AppendLine($"{indent}  const __match = {EmitExpr(matchStmt.Subject)};");
        sb.AppendLine($"{indent}  switch (__match) {{");

        for (var armIndex = 0; armIndex < matchStmt.Arms.Count; armIndex++)
        {
            var arm = matchStmt.Arms[armIndex];
            switch (arm.Pattern)
            {
                case IRLiteralPattern literalPattern:
                    sb.AppendLine($"{indent}    case {EmitValue(literalPattern.Literal)}:");
                    break;

                case IRWildcardPattern:
                    sb.AppendLine($"{indent}    default:");
                    break;

                case IRBindingPattern bindingPattern:
                    sb.AppendLine($"{indent}    default:");
                    sb.AppendLine($"{indent}      const {bindingPattern.Name} = __match;");
                    break;

                default:
                    sb.AppendLine($"{indent}    // Unsupported match pattern: {arm.Pattern.GetType().Name}");
                    continue;
            }

            EmitStatements(sb, arm.Body, indentLevel + 3, outputType, scope,
                new Dictionary<string, QueueAckBinding>(ackBindings),
                sourcePath is null ? null : $"{sourcePath}/Arms[{armIndex}]/Body");
            if (arm.BodyExpr is not null)
                sb.AppendLine($"{indent}      {EmitExpr(arm.BodyExpr)};");
            sb.AppendLine($"{indent}      break;");
        }

        sb.AppendLine($"{indent}  }}");
        sb.AppendLine($"{indent}}}");
    }

    private static string EmitCall(IRCallExpr callExpr)
    {
        if (callExpr.Callee is IRIdentExpr { Name: "__array__" })
            return $"[{string.Join(", ", callExpr.Args.Select(arg => EmitExpr(arg.Value)))}]";

        if (callExpr.Callee is IREnumAccessExpr enumAccessExpr)
        {
            return callExpr.Args.Count switch
            {
                0 => $"{{ kind: '{enumAccessExpr.Variant}' }}",
                1 => $"{{ kind: '{enumAccessExpr.Variant}', value: {EmitExpr(callExpr.Args[0].Value)} }}",
                _ => $"{EmitExpr(callExpr.Callee)}({string.Join(", ", callExpr.Args.Select(arg => EmitExpr(arg.Value)))})",
            };
        }

        if (callExpr.Callee is IRIdentExpr { Name: "__json__" })
        {
            var fields = string.Join(", ", callExpr.Args.Select(arg =>
                $"{arg.Name ?? "field"}: {EmitExpr(arg.Value)}"));
            return $"{{ {fields} }}";
        }

        if (callExpr.Callee is IRIdentExpr { Name: var castName } &&
            callExpr.Args.Count == 1 &&
            TryEmitNumericCast(castName, EmitExpr(callExpr.Args[0].Value), out var numericCast))
        {
            return numericCast;
        }

        if (callExpr.Callee is IRIdentExpr { Name: "latest" } &&
            callExpr.Args.Count == 1)
        {
            return $"{EmitExpr(callExpr.Args[0].Value)}.latest()!";
        }

        if (callExpr.Callee is IRIdentExpr { Name: "batch" } &&
            callExpr.Args.Count == 2)
        {
            return $"{EmitExpr(callExpr.Args[0].Value)}.batch({EmitExpr(callExpr.Args[1].Value)})";
        }

        // Struct literal: callee jest PascalCase i wszystkie argumenty są nazwane
        // (np. HomeAlert { alert_type: x, severity: 3 } → { alert_type: x, severity: 3 })
        if (callExpr.Callee is IRIdentExpr { Name: var sName } &&
            sName.Length > 0 && char.IsUpper(sName[0]) &&
            callExpr.Args.Count > 0 &&
            callExpr.Args.All(a => a.Name is not null))
        {
            var fields = string.Join(", ", callExpr.Args.Select(arg =>
                $"{arg.Name!}: {EmitExpr(arg.Value)}"));
            return $"{{ {fields} }}";
        }

        var args = string.Join(", ", callExpr.Args.Select(arg => EmitExpr(arg.Value)));
        return $"{EmitExpr(callExpr.Callee)}({args})";
    }

    private static bool TryEmitNumericCast(string name, string value, out string expression)
    {
        expression = name.ToLowerInvariant() switch
        {
            "f32" or "float32" => $"Math.fround(Number({value}))",
            "f64" or "float64" => $"Number({value})",
            "i8" or "int8" or
            "i16" or "int16" or
            "i32" or "int32" or
            "i64" or "int64" or
            "u8" or "uint8" or
            "u16" or "uint16" or
            "u32" or "uint32" or
            "u64" or "uint64" => $"Math.trunc(Number({value}))",
            _ => string.Empty
        };

        return expression.Length > 0;
    }

    private static string EmitValue(IRValue value) => value switch
    {
        IRIntValue intValue => intValue.Value.ToString(System.Globalization.CultureInfo.InvariantCulture),
        IRFloatValue floatValue => floatValue.Value.ToString(System.Globalization.CultureInfo.InvariantCulture),
        IRBoolValue boolValue => boolValue.Value ? "true" : "false",
        IRTextValue textValue => EmitInterpolatedString(textValue.Value),
        IRUnitValue unitValue => EmitUnitValue(unitValue),
        IRNullValue => "null",
        _ => "undefined"
    };

    private static string EmitZeroValue(IRType type) => type switch
    {
        IRNamedType { Name: "Int" } => "0",
        IRNamedType { Name: "Float" } => "0",
        IRNamedType { Name: "Bool" } => "false",
        IRNamedType { Name: "Text" } => "''",
        IRNamedType => "{}",
        IRArrayType => "[]",
        _ => "undefined"
    };

    private static string EmitDuration(IRExpr expr)
        => expr is IRLiteralExpr { Value: IRUnitValue unitValue }
            ? EmitDurationLiteral(unitValue)
            : EmitExpr(expr);

    private static string EmitUnitValue(IRUnitValue unitValue)
        => unitValue.Unit switch
        {
            "ms" or "s" or "m" or "h" => EmitDurationLiteral(unitValue),
            _ => unitValue.Magnitude.ToString(System.Globalization.CultureInfo.InvariantCulture)
        };

    private static string EmitDurationLiteral(IRUnitValue unitValue)
    {
        var magnitude = unitValue.Magnitude.ToString(System.Globalization.CultureInfo.InvariantCulture);
        return unitValue.Unit switch
        {
            "ms" => magnitude,
            "s" => $"({magnitude} * 1000)",
            "m" => $"({magnitude} * 60 * 1000)",
            "h" => $"({magnitude} * 60 * 60 * 1000)",
            _ => magnitude
        };
    }

    private static string EscapeString(string value)
        => value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("'", "\\'", StringComparison.Ordinal);

    // ─── String interpolation ────────────────────────────────────────────────

    /// <summary>
    /// Regex dopasowuje wzorce interpolacji: {expr} lub {expr:format_spec}.
    /// </summary>
    private static readonly Regex InterpolationRegex =
        new(@"\{([^{}:]+)(?::([^{}]*))?\}", RegexOptions.Compiled);

    /// <summary>
    /// Emituje wartość tekstową jako TypeScript string. Jeśli zawiera wzorce {expr},
    /// generuje template literal z ${expr}. W przeciwnym razie: zwykły string w apostrofach.
    /// </summary>
    private static string EmitInterpolatedString(string raw)
    {
        var matches = InterpolationRegex.Matches(raw);
        if (matches.Count == 0)
            return $"'{EscapeString(raw)}'";

        var sb = new StringBuilder();
        sb.Append('`');
        int lastPos = 0;
        foreach (Match m in matches)
        {
            sb.Append(EscapeTemplateLiteral(raw[lastPos..m.Index]));
            var exprPart = m.Groups[1].Value.Trim();
            var fmtSpec  = m.Groups[2].Success ? m.Groups[2].Value : null;
            sb.Append("${");
            sb.Append(ConvertInterpolationExpr(exprPart, fmtSpec));
            sb.Append('}');
            lastPos = m.Index + m.Length;
        }
        sb.Append(EscapeTemplateLiteral(raw[lastPos..]));
        sb.Append('`');
        return sb.ToString();
    }

    /// <summary>Escape dla TypeScript template literal: backslash, backtick, ${ sekwencja.</summary>
    private static string EscapeTemplateLiteral(string s)
        => s.Replace("\\", "\\\\", StringComparison.Ordinal)
             .Replace("`",  "\\`",  StringComparison.Ordinal)
             .Replace("${", "\\${", StringComparison.Ordinal);

    /// <summary>
    /// Konwertuje wyrażenie interpolacji do TypeScript.
    /// Format spec: '.Nf' → expr.toFixed(N), 'd' → Math.floor(expr), brak → expr.
    /// </summary>
    private static string ConvertInterpolationExpr(string expr, string? fmtSpec)
    {
        if (string.IsNullOrEmpty(fmtSpec))
            return expr;

        // .Nf lub .0f → expr.toFixed(N)
        if (fmtSpec.StartsWith('.') && fmtSpec.EndsWith('f'))
        {
            var prec = fmtSpec[1..^1];
            return $"{expr}.toFixed({prec})";
        }

        // d → Math.floor(expr)
        if (string.Equals(fmtSpec, "d", StringComparison.Ordinal))
            return $"Math.floor({expr})";

        return expr;
    }

    private static bool ContainsReturn(IReadOnlyList<IRStmt> statements)
        => statements.Any(statement => statement switch
        {
            IRReturnStmt => true,
            IRIfStmt ifStmt => ContainsReturn(ifStmt.Then) || ContainsReturn(ifStmt.Else),
            IREveryStmt everyStmt => ContainsReturn(everyStmt.Body),
            IRLoopStmt loopStmt => ContainsReturn(loopStmt.Body),
            IRForStmt forStmt => ContainsReturn(forStmt.Body),
            IRMatchStmt matchStmt => matchStmt.Arms.Any(arm => ContainsReturn(arm.Body)),
            _ => false,
        });

    private static bool ContainsReturn(IRElse? elseBranch)
        => elseBranch switch
        {
            IRElseIf elseIf => ContainsReturn(elseIf.IfStmt.Then) || ContainsReturn(elseIf.IfStmt.Else),
            IRElseBlock elseBlock => ContainsReturn(elseBlock.Body),
            null => false,
            _ => false,
        };
}
